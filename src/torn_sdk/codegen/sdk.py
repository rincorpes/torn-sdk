GENERATED_HEADER = (
    "# AUTO-GENERATED BY torn_sdk_codegen.py v-0.1.0. DO NOT EDIT MANUALLY "
    "outside custom blocks."
)
CLIENT_CUSTOM_HEADER_START = "# <torn-sdk:custom-header>"
CLIENT_CUSTOM_HEADER_END = "# </torn-sdk:custom-header>"
CLIENT_CUSTOM_CLASS_START = "# <torn-sdk:custom-class>"
CLIENT_CUSTOM_CLASS_END = "# </torn-sdk:custom-class>"


def custom_block(
    kind: str, *, name: str | None = None, indent: str = ""
) -> list[str]:
    """Render a user-owned region whose contents survive regeneration.

    Args:
        kind: Custom block category.
        name: Optional block name.
        indent: Prefix applied to each marker.

    Returns:
        Opening and closing marker lines.
    """
    suffix = f" {name}" if name else ""
    return [
        f"{indent}# <torn-sdk:custom-{kind}{suffix}>",
        f"{indent}# </torn-sdk:custom-{kind}{suffix}>",
    ]


def generated_module_header(description: str) -> list[str]:
    """Create a standard header with a Python-recognized module docstring.

    Args:
        description: Generated module description.

    Returns:
        Standard generated-module header lines.
    """
    return [
        f'"""{description}"""',
        *custom_block("header"),
        GENERATED_HEADER,
        "from __future__ import annotations",
        "",
    ]


class GeneratedSourceFormatter:
    """Apply the project's deterministic formatting to generated Python."""

    def __init__(self, sdk_root: Path) -> None:
        try:
            import black
            import isort
        except ImportError as exc:
            raise CodegenError(
                "SDK generation requires the 'dev' extra for Black and isort. "
                "Install it with: python -m pip install -e '.[dev]'"
            ) from exc

        self.black = black
        self.isort = isort
        self.project_root = sdk_root.parents[1]
        # CI skips generated paths when checking handwritten code, but the
        # generator must still format its own output before it is written.
        self.isort_config = isort.Config(
            settings_path=self.project_root,
            skip=(),
            skip_glob=(),
        )
        self.black_mode = black.Mode(
            line_length=79,
            target_versions={black.TargetVersion.PY310},
        )

    def format(self, source: str) -> str:
        """Format generated source without writing outside the generator root.

        Args:
            source: Complete generated Python source.

        Returns:
            Black- and isort-formatted Python source.
        """
        source, custom_header = self._extract_custom_header(source)
        # Supplying a generated file path makes isort reapply skip_glob rules.
        # The explicit config retains project import settings without skipping.
        sorted_source = self.isort.code(source, config=self.isort_config)
        formatted = self.black.format_str(sorted_source, mode=self.black_mode)
        if custom_header:
            formatted = formatted.replace(
                GENERATED_HEADER,
                f"{custom_header}\n\n{GENERATED_HEADER}",
                1,
            )
        return formatted

    @staticmethod
    def _extract_custom_header(source: str) -> tuple[str, str | None]:
        """Temporarily remove a custom header block before import sorting."""
        pattern = re.compile(
            r"^# <torn-sdk:custom-header>$\n"
            r".*?^# </torn-sdk:custom-header>$\n*",
            flags=re.MULTILINE | re.DOTALL,
        )
        match = pattern.search(source)
        if not match:
            return source, None
        header = match.group(0).rstrip()
        source_without_header = source[: match.start()] + source[match.end() :]
        return source_without_header, header


def merge_custom_blocks(path: Path, source: str) -> str:
    """Carry user-owned marked regions from an existing generated file forward.

    Args:
        path: Existing generated file path.
        source: Newly rendered generated source.

    Returns:
        Source with matching custom blocks preserved.
    """
    if not path.exists():
        return source
    existing = path.read_text(encoding="utf-8")
    pattern = re.compile(
        r"^(?P<start>\s*# <torn-sdk:custom-[^>]+>)$\n"
        r"(?P<body>.*?)^(?P<end>\s*# </torn-sdk:custom-[^>]+>)$",
        flags=re.MULTILINE | re.DOTALL,
    )
    contents = {
        match.group("start").strip(): match.group("body")
        for match in pattern.finditer(existing)
    }

    def replace(match: re.Match[str]) -> str:
        start = match.group("start")
        body = contents.get(start.strip(), match.group("body"))
        return f"{start}\n{body}{match.group('end')}"

    return pattern.sub(replace, source)


@dataclass(frozen=True)
class ClientCustomizations:
    """User-owned source kept when the generated client surface changes.

    Attributes:
        header: Preserved module-level custom lines.
        class_body: Preserved custom lines within the client class body.
    """

    header: tuple[str, ...] = ()
    class_body: tuple[str, ...] = ()


def read_client_customizations(path: Path) -> ClientCustomizations:
    """Read preserved client regions, migrating standalone directives once.

    Args:
        path: Generated client module path.

    Returns:
        Custom header and class-body content found in the module.
    """
    if not path.exists():
        return ClientCustomizations()

    source = path.read_text(encoding="utf-8")

    def section(start: str, end: str, *, indent: str = "") -> tuple[str, ...]:
        match = re.search(
            rf"^{re.escape(indent + start)}$\\n(.*?)^{re.escape(indent + end)}$",
            source,
            flags=re.MULTILINE | re.DOTALL,
        )
        if not match:
            return ()
        return tuple(
            line[len(indent) :] if line.startswith(indent) else line
            for line in match.group(1).splitlines()
        )

    header = section(CLIENT_CUSTOM_HEADER_START, CLIENT_CUSTOM_HEADER_END)
    class_body = section(
        CLIENT_CUSTOM_CLASS_START,
        CLIENT_CUSTOM_CLASS_END,
        indent="    ",
    )
    if header or class_body:
        return ClientCustomizations(header=header, class_body=class_body)

    # Migrate common handwritten file-level notes from clients generated before
    # custom blocks existed. The generated import's inline pylint directive is
    # deliberately excluded because the renderer owns it.
    header = tuple(
        line
        for line in source.splitlines()
        if line.startswith("#")
        and ("TODO" in line.upper() or "pylint:" in line.lower())
    )
    return ClientCustomizations(header=header)


