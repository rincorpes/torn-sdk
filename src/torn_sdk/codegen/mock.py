@dataclass(frozen=True)
class RawOperation:
    tag: str
    selection: str
    path: str
    http_method: str
    operation: Mapping[str, Any]


@dataclass(frozen=True)
class ParameterSpec:
    api_name: str
    python_name: str
    location: str
    required: bool


@dataclass(frozen=True)
class WrapperEndpoint:
    method_name: str
    request_path: str
    request_parameter_names: Mapping[str, str]
    notes: tuple[str, ...] = ()


@dataclass(frozen=True)
class RouteVariant:
    source_path: str
    required_params: tuple[str, ...]
    forbidden_params: tuple[str, ...]
    response: Any


@dataclass(frozen=True)
class MockRoute:
    tag: str
    selection: str
    wrapper_method: str
    request_path: str
    variants: tuple[RouteVariant, ...]


@dataclass(frozen=True)
class TagSpec:
    name: str
    routes: tuple[MockRoute, ...]


@dataclass
class GenerationPlan:
    tags: list[TagSpec] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


