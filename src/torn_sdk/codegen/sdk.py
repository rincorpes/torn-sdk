    # Useful aliases for existing public SDK names. Extend as needed.
    literal_alias_names: dict[str, str] = {
        "ApiSort": "SortType",
        "ApiFiltersAttacksRevivesEnum": "UserAttacksRequestFilterType",
    }

    # (model name, wire field name) -> field behavior.
    field_overrides: dict[tuple[str, str], FieldOverride] = {
        ("UserBasic", "id"): FieldOverride(aliases=("id", "player_id")),
    }

    # Preserve currently established User model names where known.
    endpoint_overrides: dict[tuple[str, str], EndpointOverride] = {
        ("user", "ammo"): EndpointOverride(response_model="UserAmmoResponse"),
        ("user", "attacks"): EndpointOverride(
            response_model="UserAttacksResponse"
        ),
        ("user", "attacksfull"): EndpointOverride(
            response_model="UserAttacksFullResponse"
        ),
        ("user", "bars"): EndpointOverride(response_model="UserBars"),
        ("user", "basic"): EndpointOverride(response_model="UserBasic"),
        ("user", "battlestats"): EndpointOverride(
            response_model="UserBattlestats"
        ),
        ("user", "bounties"): EndpointOverride(response_model="UserBounties"),
        ("user", "calendar"): EndpointOverride(response_model="UserCalendar"),
        ("user", "casino"): EndpointOverride(response_model="UserCasino"),
        ("user", "competition"): EndpointOverride(
            response_model="UserCompetition"
        ),
        ("user", "cooldowns"): EndpointOverride(
            response_model="UserCoolDowns"
        ),
        ("user", "discord"): EndpointOverride(response_model="UserDiscord"),
        ("user", "education"): EndpointOverride(
            response_model="UserEducation"
        ),
        ("user", "enlistedcars"): EndpointOverride(
            response_model="UserEnlistedCars"
        ),
        # CSV response: handled outside the Pydantic JSON endpoint generator.
        ("user", "snapshot"): EndpointOverride(skip=True),
    }

    def parameter(
        self, component_name: str | None
    ) -> ParameterOverride | None:
        """Return the configured override for a parameter component.

        Args:
            component_name: OpenAPI parameter component name.

        Returns:
            Configured override, if one exists.
        """
        return self.parameter_overrides.get(component_name or "")

    def field(self, model_name: str, wire_name: str) -> FieldOverride | None:
        """Return the configured override for a generated model field.

        Args:
            model_name: Generated model name.
            wire_name: Original API field name.

        Returns:
            Configured override, if one exists.
        """
        return self.field_overrides.get((model_name, wire_name))

    def endpoint(self, tag: str, selection: str) -> EndpointOverride:
        """Return the configured override for a Torn tag/selection pair.

        Args:
            tag: Normalized resource tag.
            selection: Derived endpoint selection.

        Returns:
            Endpoint override, including a default when none is configured.
        """
        if (
            selection == "generic"
            and (tag, selection) not in self.endpoint_overrides
        ):
            # Tag-root endpoints such as /user are multi-selection escape hatches.
            # The typed SDK exposes the concrete selection methods instead.
            return EndpointOverride(skip=True)
        return self.endpoint_overrides.get(
            (tag, selection), EndpointOverride()
        )

    def literal_name(self, source_name: str) -> str:
        """Return the preferred Python alias for an enum-like schema.

        Args:
            source_name: OpenAPI schema component name.

        Returns:
            Configured or convention-derived alias name.
        """
        return self.literal_alias_names.get(
            source_name, PythonNames.enum_alias(source_name)
        )


