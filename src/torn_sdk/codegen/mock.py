class TornMockGenerator:
    def __init__(
        self,
        document: OpenAPIDocument,
        *,
        wrapper_check: bool,
        strict: bool,
    ) -> None:
        self.document = document
        self.refs = RefResolver(document)
        self.discovery = EndpointDiscovery(document)
        self.parameters = ParameterPlanner(
            document,
            self.refs,
        )
        self.wrapper = TornAPIWrapperInspector(
            enabled=wrapper_check,
        )
        self.examples = SchemaExampleFactory(
            self.refs,
        )
        self.responses = ResponsePlanner(
            self.refs,
            self.examples,
        )
        self.builder = PlanBuilder(
            self.discovery,
            self.parameters,
            self.wrapper,
            self.responses,
            strict=strict,
        )
        self.renderer = ModuleRenderer()
        self.reporter = ReportRenderer()
        self.writer = FileWriter()

    def build_plan(
        self,
        selected_tags: set[str] | None = None,
    ) -> GenerationPlan:
        normalized = (
            {PythonNames.snake(tag) for tag in selected_tags}
            if selected_tags
            else None
        )
        return self.builder.build(normalized)

    def run(
        self,
        *,
        output: Path,
        selected_tags: set[str] | None,
        report: bool,
        report_file: Path | None,
        check: bool,
    ) -> int:
        plan = self.builder.build(
            selected_tags,
        )

        module = self.renderer.render(
            plan,
            openapi_version=self.document.version,
            openapi_hash=self.document.source_hash,
        )

        changed = self.writer.write(
            output,
            module,
            check=check,
        )

        report_text = self.reporter.render(
            plan,
            self.examples.warnings,
            openapi_version=self.document.version,
        )

        if report:
            print(
                report_text,
                end="",
            )

        if report_file is not None and not check:
            report_file.parent.mkdir(
                parents=True,
                exist_ok=True,
            )
            report_file.write_text(
                report_text,
                encoding="utf-8",
            )

        if check and changed:
            print(
                f"STALE {output}",
                file=sys.stderr,
            )
            return 1

        if not check:
            print(
                ("UPDATE" if changed else "UNCHANGED"),
                output,
            )

        return 0


