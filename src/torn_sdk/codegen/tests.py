GENERATED_HEADER = (
    "# AUTO-GENERATED BY torn-sdk generate tests. DO NOT EDIT MANUALLY."
)
TEST_PACKAGE_INIT = '"""Test package for the Torn SDK."""\n'


@dataclass(frozen=True)
class TestCaseIR:
    """Describe one generated synchronous and asynchronous route test case.

    Attributes:
        tag: Resource tag under test.
        endpoint: Generated SDK endpoint method name.
        source_path: OpenAPI route variant represented by the case.
        kwargs: Required method arguments and their sample values.
        response_model: Expected parsed response model name.
        expected_request_path: Wrapper request path expected for the call.
        required_request_params: Request parameters that must be present.
        forbidden_request_params: Request parameters that must be absent.
    """

    tag: str
    endpoint: str
    source_path: str
    kwargs: Mapping[str, Any]
    response_model: str
    expected_request_path: str
    required_request_params: tuple[str, ...] = ()
    forbidden_request_params: tuple[str, ...] = ()

    @property
    def test_id(self) -> str:
        """Return a stable pytest case identifier for this route variant.

        Returns:
            Readable identifier derived from the endpoint and source path.
        """
        path = self.source_path.strip("/").replace("/", "-")
        path = re.sub(r"[{}]", "", path)
        return f"{self.endpoint}-{path or 'root'}"


@dataclass(frozen=True)
class TestTagIR:
    """Group generated test cases for one Torn resource tag.

    Attributes:
        name: Normalized resource tag name.
        cases: Generated route test cases.
        sync_enabled: Whether the synchronous resource is available.
        async_enabled: Whether the asynchronous resource is available.
    """

    name: str
    cases: tuple[TestCaseIR, ...]
    sync_enabled: bool
    async_enabled: bool


@dataclass
class TestGenerationPlan:
    """Collect generated test groups and review warnings.

    Attributes:
        tags: Generated test-case groups.
        warnings: Non-fatal decisions requiring review.
    """

    tags: list[TestTagIR] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


class SampleValueFactory:
    """Create deterministic values for required SDK method arguments."""

    def __init__(self, literals: Sequence[LiteralAlias]) -> None:
        self._literals = {alias.name: alias.values for alias in literals}

    def value_for(self, type_code: str, *, name: str) -> Any:
        """Return a deterministic sample value for a generated parameter.

        Args:
            type_code: Rendered Python annotation for the parameter.
            name: Parameter name used to choose semantic string values.

        Returns:
            JSON-compatible sample argument value.

        Raises:
            ReviewRequired: If no trustworthy sample value can be generated.
        """
        code = self._without_none(type_code.strip())

        literal = self._literals.get(code)
        if literal:
            return next(
                (value for value in literal if value is not None),
                None,
            )

        union = self._split_top_level_union(code)
        if len(union) > 1:
            for branch in union:
                branch = branch.strip()
                if branch == "None":
                    continue
                return self.value_for(branch, name=name)

        if code.startswith("list[") and code.endswith("]"):
            inner = code[5:-1].strip()
            return [self.value_for(inner, name=f"{name}_item")]

        if code.startswith("dict["):
            return {}

        if code == "int":
            return 1
        if code == "float":
            return 1.0
        if code == "bool":
            return True
        if code == "str":
            lowered = name.lower()
            if "url" in lowered:
                return "https://example.test/"
            if "email" in lowered:
                return "mock@example.test"
            if "id" in lowered:
                return "1"
            return "mock"

        # Parameter type aliases should already be present in LiteralRegistry.
        # If we reach a model-ish type here, generating a fabricated argument is
        # less trustworthy than asking for review.
        raise ReviewRequired(
            f"Cannot generate a deterministic test argument for "
            f"{name}: {type_code}"
        )

    @staticmethod
    def _without_none(code: str) -> str:
        parts = [
            part.strip()
            for part in SampleValueFactory._split_top_level_union(code)
            if part.strip() != "None"
        ]
        return " | ".join(parts) if parts else "None"

    @staticmethod
    def _split_top_level_union(code: str) -> list[str]:
        depth = 0
        start = 0
        result: list[str] = []

        for index, char in enumerate(code):
            if char in "[(":
                depth += 1
            elif char in "])":
                depth -= 1
            elif char == "|" and depth == 0:
                result.append(code[start:index].strip())
                start = index + 1

        if result:
            result.append(code[start:].strip())
            return result

        return [code]


class ResourceAvailability:
    """Inspect whether public synchronous and asynchronous resources exist."""

    def __init__(self, sdk_root: Path) -> None:
        self.sdk_root = sdk_root

    def sync(self, tag: str) -> bool:
        """Return whether the synchronous public resource exists for a tag.

        Args:
            tag: Normalized resource tag.

        Returns:
            Whether the synchronous resource module exists.
        """
        return (self.sdk_root / "resources" / f"{tag}.py").exists()

    def async_(self, tag: str) -> bool:
        """Return whether the asynchronous public resource exists for a tag.

        Args:
            tag: Normalized resource tag.

        Returns:
            Whether the asynchronous resource module exists.
        """
        return (self.sdk_root / "resources" / f"{tag}_async.py").exists()


class TestPlanBuilder:
    """Build pytest contract cases from SDK and mock generation plans."""

    """Build pytest cases from SDK endpoints that also exist in the mock plan."""

    _PATH_PARAM_RE = re.compile(r"\{([^}]+)\}")

    def __init__(
        self,
        *,
        literals: Sequence[LiteralAlias],
        availability: ResourceAvailability,
        strict: bool = False,
    ) -> None:
        self.values = SampleValueFactory(literals)
        self.availability = availability
        self.strict = strict

    def build(
        self,
        sdk_plan: SDKGenerationPlan,
        mock_plan: MockGenerationPlan,
    ) -> TestGenerationPlan:
        """Build generated pytest cases from SDK and mock generation plans.

        Args:
            sdk_plan: Generated SDK endpoint plan.
            mock_plan: Generated mock route plan.

        Returns:
            Generated pytest test-case plan.

        Raises:
            ReviewRequired: If strict mode encounters an unsupported test case.
        """
        mock_routes = {
            (tag.name, route.selection): route
            for tag in mock_plan.tags
            for route in tag.routes
        }

        output = TestGenerationPlan()

        for sdk_tag in sdk_plan.tags:
            sync_enabled = self.availability.sync(sdk_tag.name)
            async_enabled = self.availability.async_(sdk_tag.name)

            if not sync_enabled and not async_enabled:
                output.warnings.append(
                    f"SKIPPED {sdk_tag.name}: no public resource module exists"
                )
                continue

            cases: list[TestCaseIR] = []

            for endpoint in sdk_tag.endpoints:
                route = mock_routes.get((sdk_tag.name, endpoint.name))
                if route is None:
                    output.warnings.append(
                        f"SKIPPED {sdk_tag.name}.{endpoint.name}: "
                        "no generated mock route"
                    )
                    continue

                try:
                    cases.extend(self._endpoint_cases(endpoint, route))
                except ReviewRequired as exc:
                    if self.strict:
                        raise
                    output.warnings.append(
                        f"SKIPPED {sdk_tag.name}.{endpoint.name}: {exc}"
                    )

            if cases:
                output.tags.append(
                    TestTagIR(
                        name=sdk_tag.name,
                        cases=tuple(cases),
                        sync_enabled=sync_enabled,
                        async_enabled=async_enabled,
                    )
                )

        return output

    def _endpoint_cases(
        self,
        endpoint: EndpointIR,
        route: MockRoute,
    ) -> list[TestCaseIR]:
        route_variants = {
            variant.source_path: variant for variant in route.variants
        }

        cases: list[TestCaseIR] = []

        for source_path in endpoint.source_paths:
            variant = route_variants.get(source_path)
            if variant is None:
                # The mock plan intentionally excludes unsupported OpenAPI variants,
                # e.g. an ID route TornAPIWrapper cannot represent.
                continue

            kwargs: dict[str, Any] = {}
            path_tokens = set(self._PATH_PARAM_RE.findall(source_path))

            for parameter in endpoint.parameters:
                should_supply = parameter.required

                if (
                    parameter.location == "path"
                    and parameter.wire_name in path_tokens
                ):
                    should_supply = True

                if not should_supply:
                    continue

                if (
                    parameter.default is not MISSING
                    and parameter.default is not None
                ):
                    kwargs[parameter.python_name] = parameter.default
                    continue

                kwargs[parameter.python_name] = self.values.value_for(
                    parameter.type_ref.code,
                    name=parameter.python_name,
                )

            cases.append(
                TestCaseIR(
                    tag=endpoint.tag,
                    endpoint=endpoint.name,
                    source_path=source_path,
                    kwargs=kwargs,
                    response_model=endpoint.response.public_model_name,
                    expected_request_path=route.request_path,
                    required_request_params=variant.required_params,
                    forbidden_request_params=variant.forbidden_params,
                )
            )

        if not cases:
            raise ReviewRequired(
                "SDK endpoint has no OpenAPI variant supported by the mock"
            )

        return cases


class PytestModuleRenderer:
    """Render pytest modules that exercise generated resource contracts."""

    def __init__(
        self,
        *,
        mock_module: str,
    ) -> None:
        self.mock_module = mock_module

    def render(self, tag: TestTagIR) -> str:
        """Render one generated pytest module for a Torn resource tag.

        Args:
            tag: Generated test cases for one resource.

        Returns:
            Complete pytest module source.
        """
        models = sorted({case.response_model for case in tag.cases})

        lines = [
            GENERATED_HEADER,
            "from __future__ import annotations",
            "",
            "import asyncio",
            "",
            "import pytest",
            "",
            "from torn_sdk.client import TornClient",
            "from torn_sdk.client_async import AsyncTornClient",
            f"from torn_sdk.models.{tag.name} import (",
        ]

        for model in models:
            lines.append(f"    {model},")
        lines.extend(
            [
                ")",
                f"from {self.mock_module} import (",
                "    MockTornAPIWrapper,",
                "    MockTornAPIWrapperAsync,",
                ")",
                "",
                "",
                "CASES = [",
            ]
        )

        for case in tag.cases:
            lines.extend(
                [
                    "    pytest.param(",
                    f"        {case.endpoint!r},",
                    f"        {dict(case.kwargs)!r},",
                    f"        {case.response_model},",
                    f"        {case.expected_request_path!r},",
                    f"        {case.required_request_params!r},",
                    f"        {case.forbidden_request_params!r},",
                    f"        id={case.test_id!r},",
                    "    ),",
                ]
            )

        lines.extend(
            [
                "]",
                "",
                "",
                "def _assert_request(",
                "    client,",
                "    expected_path: str,",
                "    required_params: tuple[str, ...],",
                "    forbidden_params: tuple[str, ...],",
                ") -> None:",
                "    call = client._wrapper.calls[-1]",
                "    assert call.endpoint.casefold() == expected_path.casefold()",
                "    for name in required_params:",
                "        assert call.params.get(name) is not None",
                "    for name in forbidden_params:",
                "        assert call.params.get(name) is None",
                "",
            ]
        )

        if tag.sync_enabled:
            lines.extend(
                [
                    "",
                    "@pytest.mark.parametrize(",
                    '    ("method_name", "kwargs", "model_type", "expected_path", '
                    '"required_params", "forbidden_params"),',
                    "    CASES,",
                    ")",
                    f"def test_{tag.name}_generated_contract(",
                    "    monkeypatch,",
                    "    method_name,",
                    "    kwargs,",
                    "    model_type,",
                    "    expected_path,",
                    "    required_params,",
                    "    forbidden_params,",
                    ") -> None:",
                    "    monkeypatch.setattr(",
                    '        "torn_sdk.client.TornAPIWrapper",',
                    "        MockTornAPIWrapper,",
                    "    )",
                    '    client = TornClient("mock-api-key")',
                    f"    resource = client.{tag.name}",
                    "    result = getattr(resource, method_name)(**kwargs)",
                    "    assert isinstance(result, model_type)",
                    "    _assert_request(",
                    "        client,",
                    "        expected_path,",
                    "        required_params,",
                    "        forbidden_params,",
                    "    )",
                    "",
                ]
            )

        if tag.async_enabled:
            lines.extend(
                [
                    "",
                    "@pytest.mark.parametrize(",
                    '    ("method_name", "kwargs", "model_type", "expected_path", '
                    '"required_params", "forbidden_params"),',
                    "    CASES,",
                    ")",
                    f"def test_{tag.name}_generated_contract_async(",
                    "    monkeypatch,",
                    "    method_name,",
                    "    kwargs,",
                    "    model_type,",
                    "    expected_path,",
                    "    required_params,",
                    "    forbidden_params,",
                    ") -> None:",
                    "    monkeypatch.setattr(",
                    '        "torn_sdk.client_async.TornAPIWrapperAsync",',
                    "        MockTornAPIWrapperAsync,",
                    "    )",
                    "",
                    "    async def run() -> None:",
                    '        async with AsyncTornClient("mock-api-key") as client:',
                    f"            resource = client.{tag.name}",
                    "            result = await getattr(resource, method_name)(**kwargs)",
                    "            assert isinstance(result, model_type)",
                    "            _assert_request(",
                    "                client,",
                    "                expected_path,",
                    "                required_params,",
                    "                forbidden_params,",
                    "            )",
                    "",
                    "    asyncio.run(run())",
                    "",
                ]
            )

        return "\n".join(lines).rstrip() + "\n"


class TestReportRenderer:
    """Render a human-readable generated-test report."""

    def render(self, plan: TestGenerationPlan) -> str:
        """Render a text report for generated pytest contract cases.

        Args:
            plan: Generated pytest test-case plan.

        Returns:
            Human-readable test-generation report.
        """
        total = sum(len(tag.cases) for tag in plan.tags)
        lines = [
            "Torn generated pytest contract report",
            f"Generated {len(plan.tags)} tags / {total} route cases",
            "",
        ]

        for tag in plan.tags:
            modes = []
            if tag.sync_enabled:
                modes.append("sync")
            if tag.async_enabled:
                modes.append("async")

            lines.append(f"{tag.name.upper()} ({', '.join(modes)})")
            for case in tag.cases:
                lines.append(
                    f"  {case.test_id}: {case.response_model} "
                    f"-> {case.expected_request_path}"
                )
            lines.append("")

        if plan.warnings:
            lines.append("WARNINGS")
            for warning in plan.warnings:
                lines.append(f"  - {warning}")

        return "\n".join(lines).rstrip() + "\n"


class TornTestGenerator:
    """Coordinate generation of Torn SDK pytest contract tests."""

    """Generate network-free pytest contract tests for generated SDK resources."""

    def __init__(
        self,
        document: OpenAPIDocument,
        *,
        sdk_root: Path,
        test_root: Path,
        mock_module: str = "tests.generated.mock_torn_api_wrapper",
        strict: bool = False,
        skip_wrapper_check: bool = False,
        check: bool = False,
        dry_run: bool = False,
        prune: bool = False,
    ) -> None:
        self.document = document
        self.sdk_root = sdk_root
        self.test_root = test_root
        self.mock_module = mock_module
        self.strict = strict
        self.skip_wrapper_check = skip_wrapper_check
        self.check = check
        self.dry_run = dry_run
        self.prune = prune
        self.reports = TestReportRenderer()
        self.report_exporter = ReportExporter()

    def build_plan(
        self,
        selected_tags: set[str] | None = None,
    ) -> TestGenerationPlan:
        """Build the generated-test plan for the selected tags.

        Args:
            selected_tags: Optional normalized resource tags to include.

        Returns:
            Generated pytest test-case plan.
        """
        sdk_generator = TornSDKGenerator(
            self.document,
            self.sdk_root,
            strict=self.strict,
            skip_wrapper_check=self.skip_wrapper_check,
            dry_run=True,
        )
        sdk_plan = sdk_generator.build_plan(selected_tags)

        mock_generator = TornMockGenerator(
            self.document,
            wrapper_check=not self.skip_wrapper_check,
            strict=self.strict,
        )
        mock_plan = mock_generator.build_plan(selected_tags)

        builder = TestPlanBuilder(
            literals=sdk_generator.literals.aliases,
            availability=ResourceAvailability(self.sdk_root),
            strict=self.strict,
        )
        return builder.build(sdk_plan, mock_plan)

    def generate(
        self,
        selected_tags: set[str] | None = None,
    ) -> tuple[TestGenerationPlan, GeneratedFileManager]:
        """Generate pytest contract modules and return the plan plus changes.

        Args:
            selected_tags: Optional normalized resource tags to generate.

        Returns:
            Generated test plan and tracked file changes.
        """
        plan = self.build_plan(selected_tags)
        files = GeneratedFileManager(
            self.test_root,
            check=self.check,
            dry_run=self.dry_run,
            prune=self.prune,
        )
        package_files = GeneratedFileManager(
            self.test_root.parent,
            check=self.check,
            dry_run=self.dry_run,
        )

        # Generated modules use the ``tests.generated`` import path. Scaffold
        # the parent package without taking ownership of handwritten test code.
        package_files.scaffold(Path("__init__.py"), TEST_PACKAGE_INIT)
        files.changes.extend(package_files.changes)

        renderer = PytestModuleRenderer(
            mock_module=self.mock_module,
        )

        files.emit(
            Path("__init__.py"),
            GENERATED_HEADER + "\n",
        )

        for tag in plan.tags:
            files.emit(
                Path(f"test_{tag.name}_generated.py"),
                renderer.render(tag),
            )

        if selected_tags:
            expected_tags = {PythonNames.snake(tag) for tag in selected_tags}
            files.find_stale(Path(".") for _ in ())
            # Partial generation must never prune unrelated tag tests.
            for tag in expected_tags:
                candidate = self.test_root / f"test_{tag}_generated.py"
                if candidate.exists() and candidate not in files.expected:
                    files.find_stale_paths([Path(candidate.name)])
        else:
            files.find_stale([Path(".")])

        return plan, files
