#!/usr/bin/env python3
"""Generate an OpenAPI-backed, network-free TornAPIWrapper test double.

The generated module subclasses TornAPIWrapper/TornAPIWrapperAsync but uses the
REAL wrapper endpoint classes. Only the network request boundary is replaced.

That gives tests this stack:

    Torn SDK client/resource/decorator/parser
                  |
         real TornAPIWrapper endpoint
                  |
         real build_params()/mapping
                  |
        MockTornAPIWrapper.request()
                  |
       deterministic OpenAPI response

No Torn API request is made.

Typical usage:

    python torn_mock_codegen.py openapi.json \
        --output tests/generated/mock_torn_api_wrapper.py \
        --report-file reports/mock.txt

Then in pytest:

    monkeypatch.setattr("torn_sdk.client.TornAPIWrapper", MockTornAPIWrapper)
    client = TornClient("test")
    result = client.user.basic()

For async:

    monkeypatch.setattr(
        "torn_sdk.client_async.TornAPIWrapperAsync",
        MockTornAPIWrapperAsync,
    )

By default the generator inspects the installed TornAPIWrapper and skips
OpenAPI operations the wrapper cannot service. Use --skip-wrapper-check only
to debug OpenAPI generation in isolation.
"""

