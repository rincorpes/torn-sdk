class LiteralRegistry:
    """Track reusable Literal aliases discovered during generation."""

    def __init__(self, overrides: TornOverrides) -> None:
        self.overrides = overrides
        self._aliases: dict[str, LiteralAlias] = {}
        self._signature_to_name: dict[tuple[Any, ...], str] = {}

    def register(self, source_name: str, values: Sequence[Any]) -> str:
        """Register or reuse a Literal alias for the given values.

        Args:
            source_name: Source OpenAPI component name.
            values: Permitted enum or constant values.

        Returns:
            Public alias name for the values.

        Raises:
            ReviewRequired: If the preferred alias has conflicting values.
        """
        signature = tuple(values)
        preferred = self.overrides.literal_name(source_name)
        if preferred in self._aliases:
            current = self._aliases[preferred]
            if current.values != signature:
                raise ReviewRequired(
                    f"Literal alias collision for {preferred}: "
                    f"{current.values!r} vs {signature!r}"
                )
            return preferred
        # Reuse identical enum only if doing so does not erase an explicitly
        # named override. Stable names are more useful than maximal dedupe.
        if source_name not in self.overrides.literal_alias_names:
            existing = self._signature_to_name.get(signature)
            if existing:
                return existing
        alias = LiteralAlias(preferred, signature)
        self._aliases[preferred] = alias
        self._signature_to_name.setdefault(signature, preferred)
        return preferred

    @property
    def aliases(self) -> tuple[LiteralAlias, ...]:
        """Return registered Literal aliases in deterministic name order.

        Returns:
            Registered aliases sorted by public name.
        """
        return tuple(self._aliases[name] for name in sorted(self._aliases))


class SchemaTypeResolver:
    """Resolve OpenAPI schemas into Python type annotations."""

    def __init__(
        self,
        document: OpenAPIDocument,
        refs: RefResolver,
        literals: LiteralRegistry,
    ) -> None:
        self.document = document
        self.refs = refs
        self.literals = literals

    def resolve_type(
        self, schema: Mapping[str, Any], *, source_name: str
    ) -> TypeRef:
        """Resolve a schema node into a Python annotation reference.

        Args:
            schema: OpenAPI schema node to resolve.
            source_name: Component or contextual name for generated aliases.

        Returns:
            Renderable Python type reference.

        Raises:
            ReviewRequired: If the schema cannot be represented safely.
        """
        ref_name = self.refs.ref_name(schema)
        if ref_name:
            target = self.refs.resolve(schema)
            # Only object/array/composed-object schemas become Pydantic classes.
            # Scalar refs and scalar unions are resolved to their Python value
            # types so resource signatures never contain unimported schema names.
            if isinstance(target, dict) and self._schema_is_model(target):
                return TypeRef(ref_name)
            if not isinstance(target, dict):
                raise ReviewRequired(f"Invalid referenced schema: {ref_name}")
            return self.resolve_type(target, source_name=ref_name)

        if "enum" in schema:
            values = schema.get("enum") or []
            if not isinstance(values, list) or not values:
                raise ReviewRequired(f"Invalid enum schema for {source_name}")
            alias = self.literals.register(source_name, values)
            return TypeRef(alias, frozenset({alias}))

        if "const" in schema:
            alias = self.literals.register(source_name, [schema["const"]])
            return TypeRef(alias, frozenset({alias}))

        if "oneOf" in schema or "anyOf" in schema:
            branches = schema.get("oneOf") or schema.get("anyOf") or []
            refs = [
                self.resolve_type(
                    branch, source_name=f"{source_name}Variant{idx + 1}"
                )
                for idx, branch in enumerate(branches)
            ]
            return self._union(refs)

        if "allOf" in schema:
            branches = schema.get("allOf") or []
            # For type annotations, an allOf that is merely one ref is that ref.
            if len(branches) == 1:
                return self.resolve_type(branches[0], source_name=source_name)
            # Object allOf is rendered as a model; nested annotation use falls
            # back to the source component name if available, otherwise review.
            raise ReviewRequired(
                f"Inline allOf annotation requires model normalization: {source_name}"
            )

        schema_type = schema.get("type")
        if isinstance(schema_type, list):
            branches = []
            for item in schema_type:
                if item == "null":
                    branches.append(TypeRef("None"))
                else:
                    branches.append(
                        self.resolve_type(
                            {**schema, "type": item}, source_name=source_name
                        )
                    )
            return self._union(branches)

        if schema_type == "null":
            return TypeRef("None")
        if schema_type == "integer":
            return TypeRef("int")
        if schema_type == "number":
            return TypeRef("float")
        if schema_type == "boolean":
            return TypeRef("bool")
        if schema_type == "string" or (
            schema_type is None and "format" in schema
        ):
            return TypeRef("str")
        if schema_type == "array":
            items = schema.get("items")
            if not isinstance(items, dict):
                raise ReviewRequired(f"Array without items: {source_name}")
            item_type = self.resolve_type(
                items, source_name=f"{source_name}Item"
            )
            return TypeRef(f"list[{item_type.code}]", item_type.aliases)
        if schema_type == "object" or "properties" in schema:
            if schema.get("additionalProperties"):
                additional = schema["additionalProperties"]
                if additional is True:
                    return TypeRef("dict[str, object]")
                if isinstance(additional, dict):
                    value = self.resolve_type(
                        additional, source_name=f"{source_name}Value"
                    )
                    return TypeRef(f"dict[str, {value.code}]", value.aliases)
            # Inline object schemas need a generated named model.
            return TypeRef(source_name)

        raise ReviewRequired(
            f"Unsupported schema type for {source_name}: {schema!r}"
        )

    @staticmethod
    def _union(types: Sequence[TypeRef]) -> TypeRef:
        codes: list[str] = []
        aliases: set[str] = set()
        for type_ref in types:
            if type_ref.code not in codes:
                codes.append(type_ref.code)
            aliases.update(type_ref.aliases)
        return TypeRef(" | ".join(codes), frozenset(aliases))

    def _schema_is_model(self, schema: Mapping[str, Any]) -> bool:
        if "enum" in schema or "const" in schema:
            return False
        schema_type = schema.get("type")
        if schema_type in {"object", "array"} or "properties" in schema:
            return True
        if "allOf" in schema:
            return True
        if "oneOf" in schema or "anyOf" in schema:
            branches = schema.get("oneOf") or schema.get("anyOf") or []
            for branch in branches:
                if not isinstance(branch, dict):
                    continue
                ref_name = self.refs.ref_name(branch)
                target = self.refs.resolve(branch) if ref_name else branch
                if isinstance(target, dict) and self._schema_is_model(target):
                    return True
            return False
        return False

    @staticmethod
    def _is_scalar_like(schema: Mapping[str, Any]) -> bool:
        if "enum" in schema or "const" in schema:
            return True
        schema_type = schema.get("type")
        if schema_type in {"string", "integer", "number", "boolean", "null"}:
            return True
        if isinstance(schema_type, list):
            return all(
                t in {"string", "integer", "number", "boolean", "null"}
                for t in schema_type
            )
        if "oneOf" in schema or "anyOf" in schema:
            return all(
                isinstance(branch, dict)
                and "$ref" not in branch
                and SchemaTypeResolver._is_scalar_like(branch)
                for branch in (
                    schema.get("oneOf") or schema.get("anyOf") or []
                )
            )
        return False


class EndpointDiscovery:
    """Discover supported OpenAPI operations grouped by Torn resource tag."""

    HTTP_METHODS = {"get", "post", "put", "patch", "delete"}

    def __init__(self, document: OpenAPIDocument) -> None:
        self.document = document

    def discover(
        self, selected_tags: set[str] | None = None
    ) -> list[RawOperation]:
        """Return supported OpenAPI operations for the selected tags.

        Args:
            selected_tags: Optional normalized resource tags to include.

        Returns:
            Discovered supported OpenAPI operations.
        """
        results: list[RawOperation] = []
        normalized_filter = (
            {PythonNames.snake(t) for t in selected_tags}
            if selected_tags
            else None
        )
        for path, path_item in self.document.paths.items():
            if not isinstance(path_item, dict):
                continue
            for method, operation in path_item.items():
                if method.lower() not in self.HTTP_METHODS or not isinstance(
                    operation, dict
                ):
                    continue
                tags = operation.get("tags", [])
                if not tags:
                    continue
                for raw_tag in tags:
                    tag = PythonNames.snake(str(raw_tag))
                    if (
                        normalized_filter is not None
                        and tag not in normalized_filter
                    ):
                        continue
                    selection = self.selection(path, tag)
                    results.append(
                        RawOperation(
                            tag=tag,
                            path=path,
                            http_method=method.lower(),
                            selection=selection,
                            operation_id=operation.get("operationId"),
                            operation=operation,
                        )
                    )
        return results

    @staticmethod
    def selection(path: str, tag: str) -> str:
        """Derive the SDK selection name from an OpenAPI path.

        Args:
            path: OpenAPI path template.
            tag: Normalized resource tag.

        Returns:
            Derived normalized endpoint selection.
        """
        parts = [part for part in path.strip("/").split("/") if part]
        static = [
            part
            for part in parts
            if not (part.startswith("{") and part.endswith("}"))
        ]
        if static and PythonNames.snake(static[0]) == tag:
            static = static[1:]
        if not static:
            return "generic"
        # Torn v2 selections are currently represented by the final static segment.
        return PythonNames.snake(static[-1])


@dataclass(frozen=True)
class ParameterCandidate:
    """Describe one unresolved OpenAPI parameter before signature merging.

    Attributes:
        component_name: Source component name, if referenced.
        wire_name: Original API parameter name.
        location: OpenAPI parameter location.
        required: Whether the source contract requires it.
        schema: Resolved parameter schema.
    """

    component_name: str | None
    wire_name: str
    location: str
    required: bool
    schema: Mapping[str, Any]


class ParameterNormalizer:
    """Normalize OpenAPI parameters into Torn SDK Python signatures."""

    def __init__(
        self,
        refs: RefResolver,
        types: SchemaTypeResolver,
        overrides: TornOverrides,
    ) -> None:
        self.refs = refs
        self.types = types
        self.overrides = overrides

    def parse_operation(self, raw: RawOperation) -> list[ParameterCandidate]:
        """Parse one OpenAPI operation into normalized parameter candidates.

        Args:
            raw: Discovered OpenAPI operation.

        Returns:
            Supported path and query parameter candidates.

        Raises:
            ReviewRequired: If a parameter cannot be normalized safely.
        """
        result: list[ParameterCandidate] = []
        for parameter_node in raw.operation.get("parameters", []):
            if not isinstance(parameter_node, dict):
                continue
            component_name = self.refs.ref_name(parameter_node)
            parameter = self.refs.resolve(parameter_node)
            if not isinstance(parameter, dict):
                raise ReviewRequired(f"Invalid parameter in {raw.path}")
            override = self.overrides.parameter(component_name)
            if override and override.omit:
                continue
            # Authentication is a client concern, not an endpoint argument.
            if component_name and component_name.startswith("ApiKey"):
                continue
            wire_name = str(parameter.get("name", ""))
            if not wire_name:
                raise ReviewRequired(f"Parameter without name in {raw.path}")
            location = str(parameter.get("in", "query"))
            if location not in {"path", "query"}:
                continue
            schema = parameter.get("schema")
            if not isinstance(schema, dict):
                raise ReviewRequired(
                    f"Parameter {wire_name} has no schema in {raw.path}"
                )
            result.append(
                ParameterCandidate(
                    component_name=component_name,
                    wire_name=wire_name,
                    location=location,
                    required=bool(parameter.get("required", False)),
                    schema=schema,
                )
            )
        return result

    def merge(
        self, tag: str, raw_ops: Sequence[RawOperation]
    ) -> tuple[ParameterIR, ...]:
        """Merge multiple route variants into one SDK method signature.

        Args:
            tag: Resource tag that owns the operations.
            raw_ops: Operations represented by one SDK endpoint.

        Returns:
            Shared normalized SDK parameters.

        Raises:
            MergeConflict: If operation parameters are incompatible.
            ReviewRequired: If a parameter cannot be represented safely.
        """
        per_operation = [self.parse_operation(op) for op in raw_ops]
        keys: list[tuple[str, str]] = []
        for candidates in per_operation:
            for candidate in candidates:
                key = (candidate.location, candidate.wire_name)
                if key not in keys:
                    keys.append(key)

        merged: list[ParameterIR] = []
        for location, wire_name in keys:
            appearances: list[ParameterCandidate] = []
            for candidates in per_operation:
                match = next(
                    (
                        c
                        for c in candidates
                        if c.location == location and c.wire_name == wire_name
                    ),
                    None,
                )
                if match:
                    appearances.append(match)
            first = appearances[0]
            # The same named parameter must have compatible schemas across variants.
            fingerprints = {self._fingerprint(c.schema) for c in appearances}
            if len(fingerprints) > 1:
                raise MergeConflict(
                    f"Parameter {wire_name!r} differs across merged operations: "
                    f"{', '.join(op.path for op in raw_ops)}"
                )

            override = self.overrides.parameter(first.component_name)
            source_name = first.component_name or (
                f"{PythonNames.pascal(tag)}"
                f"{PythonNames.pascal(raw_ops[0].selection)}"
                f"{PythonNames.pascal(wire_name)}"
            )
            if override and override.python_type:
                type_ref = TypeRef(override.python_type)
            else:
                type_ref = self.types.resolve_type(
                    first.schema, source_name=source_name
                )

            if location == "path":
                python_name, _ = PythonNames.path_parameter(wire_name, tag)
            else:
                python_name, _ = PythonNames.identifier(wire_name)
            if override and override.python_name:
                python_name = override.python_name

            # Required only if present and required in every operation. A path id
            # that exists only in /tag/{id}/selection becomes optional when paired
            # with /tag/selection.
            present_everywhere = len(appearances) == len(per_operation)
            required = present_everywhere and all(
                c.required for c in appearances
            )

            default = MISSING
            if override and override.default is not MISSING:
                default = override.default
            elif "default" in first.schema:
                default = first.schema["default"]
            elif not required:
                default = None

            if not required and default is None:
                type_ref = type_ref.optional()

            merged.append(
                ParameterIR(
                    wire_name=wire_name,
                    python_name=python_name,
                    location=location,  # type: ignore[arg-type]
                    type_ref=type_ref,
                    required=required,
                    default=default,
                    source_component=first.component_name,
                )
            )

        # Path args first, then query args. Preserve OpenAPI order within each class.
        merged.sort(key=lambda p: 0 if p.location == "path" else 1)
        return tuple(merged)

    @staticmethod
    def _fingerprint(schema: Mapping[str, Any]) -> str:
        return json.dumps(schema, sort_keys=True, separators=(",", ":"))


@dataclass(frozen=True)
class WrapperEndpointSupport:
    """Describe the wrapper method and parameters matched for an endpoint.

    Attributes:
        method_name: TornAPIWrapper method name.
        parameters: Wrapper-compatible SDK parameters.
        notes: Compatibility notes retained in reports.
    """

    method_name: str
    parameters: tuple[ParameterIR, ...]
    notes: tuple[str, ...] = ()


class TornAPIWrapperInspector:
    """Match OpenAPI operations to callable TornAPIWrapper endpoint methods."""

    """Use installed TornAPIWrapper as the transport/callable source of truth.

    OpenAPI names and TornAPIWrapper method names are intentionally treated as
    independent things.  In particular Torn selections such as ``revivesFull``
    may be represented by an SDK method ``revives_full`` while TornAPIWrapper
    exposes ``get_revivesfull``.

    Resolution order:
      1. Find the wrapper method whose ``self.api.request('/tag/selection', ...)``
         path matches the OpenAPI operation path after removing path parameters.
      2. Fall back to the explicitly preferred method name.
      3. Fall back to a separator-insensitive method-name match.

    OpenAPI remains authoritative for parameter types and response schemas;
    TornAPIWrapper remains authoritative for callable method/parameter names.
    """

    _REQUEST_RE = re.compile(
        r"""(?:self\.)?api\.request\(\s*[furbFURB]*["']([^"']+)["']"""
    )

    def __init__(self, *, enabled: bool = True) -> None:
        self.enabled = enabled
        self._parameter_map: Mapping[str, str] = {}
        self._module_cache: dict[tuple[str, str], Any] = {}
        self._resource_cache: dict[tuple[str, str], Any] = {}
        self._method_index_cache: dict[
            tuple[str, str], dict[str, list[tuple[str, Any]]]
        ] = {}
        if enabled:
            self._load_parameter_map()

    def _load_parameter_map(self) -> None:
        try:
            module = importlib.import_module("TornAPIWrapper.params.map")
        except Exception as exc:
            raise CodegenError(
                "TornAPIWrapper is required for wrapper compatibility checks. "
                "Install the project dependency or pass --skip-wrapper-check."
            ) from exc
        mapping = getattr(module, "parameter_map", None)
        if not isinstance(mapping, Mapping):
            raise CodegenError(
                "TornAPIWrapper.params.map.parameter_map is unavailable or invalid"
            )
        self._parameter_map = mapping

    def inspect_endpoint(
        self,
        tag: str,
        preferred_method: str,
        parameters: Sequence[ParameterIR],
        source_paths: Sequence[str] = (),
    ) -> WrapperEndpointSupport:
        """Match an SDK endpoint to TornAPIWrapper sync and async methods.

        Args:
            tag: Resource tag to inspect.
            preferred_method: Preferred wrapper method name.
            parameters: Normalized SDK method parameters.
            source_paths: OpenAPI paths represented by the endpoint.

        Returns:
            Compatible wrapper endpoint support details.

        Raises:
            WrapperUnsupported: If no wrapper method can serve the endpoint.
        """
        if not self.enabled:
            return WrapperEndpointSupport(
                preferred_method,
                tuple(parameters),
            )

        sync_name, sync_method = self._resolve_method(
            "endpoints",
            tag,
            preferred_method,
            source_paths,
        )
        async_name, async_method = self._resolve_method(
            "endpoints_async",
            tag,
            preferred_method,
            source_paths,
        )

        if sync_name != async_name:
            raise WrapperUnsupported(
                f"TornAPIWrapper sync/async methods differ for {tag}: "
                f"sync={sync_name}, async={async_name}"
            )

        sync_signature = self._call_signature(sync_method)
        async_signature = self._call_signature(async_method)
        sync_names = tuple(sync_signature)
        async_names = tuple(async_signature)
        if sync_names != async_names:
            raise WrapperUnsupported(
                f"TornAPIWrapper sync/async signatures differ for {tag}.{sync_name}: "
                f"sync={sync_names}, async={async_names}"
            )

        aligned = self._align_parameters(
            tag,
            sync_name,
            parameters,
            sync_signature,
        )
        return WrapperEndpointSupport(
            method_name=sync_name,
            parameters=aligned.parameters,
            notes=aligned.notes,
        )

    def _module(self, package: str, tag: str) -> Any:
        key = (package, tag)
        if key in self._module_cache:
            return self._module_cache[key]
        module_name = f"TornAPIWrapper.{package}.{tag}"
        try:
            module = importlib.import_module(module_name)
        except Exception as exc:
            raise WrapperUnsupported(
                f"TornAPIWrapper does not provide module {module_name}"
            ) from exc
        self._module_cache[key] = module
        return module

    def _resource_type(self, package: str, tag: str) -> Any:
        key = (package, tag)
        if key in self._resource_cache:
            return self._resource_cache[key]
        module = self._module(package, tag)
        class_name = PythonNames.pascal(tag)
        resource_type = getattr(module, class_name, None)
        if resource_type is None:
            raise WrapperUnsupported(
                f"TornAPIWrapper.{package}.{tag} has no {class_name} endpoint class"
            )
        self._resource_cache[key] = resource_type
        return resource_type

    def _resolve_method(
        self,
        package: str,
        tag: str,
        preferred_method: str,
        source_paths: Sequence[str],
    ) -> tuple[str, Any]:
        resource_type = self._resource_type(package, tag)
        index = self._method_index(package, tag)

        target_paths = {
            self._normalize_request_path(path) for path in source_paths if path
        }
        path_matches: list[tuple[str, Any]] = []
        for target in sorted(target_paths):
            path_matches.extend(index.get(target, ()))
        path_matches = self._unique_methods(path_matches)

        if len(path_matches) == 1:
            return path_matches[0]
        if len(path_matches) > 1:
            raise WrapperUnsupported(
                f"multiple TornAPIWrapper methods map to {sorted(target_paths)}: "
                f"{[name for name, _ in path_matches]}"
            )

        # Explicit override / historical default.
        exact = getattr(resource_type, preferred_method, None)
        if exact is not None and callable(exact):
            return preferred_method, exact

        # TornAPIWrapper frequently flattens compound Torn selection names:
        # revives_full -> get_revivesfull, attacks_full -> get_attacksfull, etc.
        target_key = self._method_key(preferred_method)
        name_matches = [
            (name, method)
            for name, method in inspect.getmembers(
                resource_type, predicate=callable
            )
            if name.startswith("get_") and self._method_key(name) == target_key
        ]
        name_matches = self._unique_methods(name_matches)
        if len(name_matches) == 1:
            return name_matches[0]
        if len(name_matches) > 1:
            raise WrapperUnsupported(
                f"ambiguous TornAPIWrapper method match for {tag}.{preferred_method}: "
                f"{[name for name, _ in name_matches]}"
            )

        side = "async" if package.endswith("_async") else "sync"
        source_text = ", ".join(sorted(source_paths)) or "<unknown path>"
        raise WrapperUnsupported(
            f"TornAPIWrapper {side} {PythonNames.pascal(tag)} has no method "
            f"mapped to {source_text} (preferred {preferred_method}())"
        )

    def _method_index(
        self,
        package: str,
        tag: str,
    ) -> dict[str, list[tuple[str, Any]]]:
        cache_key = (package, tag)
        cached = self._method_index_cache.get(cache_key)
        if cached is not None:
            return cached

        resource_type = self._resource_type(package, tag)
        index: dict[str, list[tuple[str, Any]]] = defaultdict(list)
        for name, method in inspect.getmembers(
            resource_type, predicate=callable
        ):
            if not name.startswith("get_"):
                continue
            request_path = self._request_path_from_method(method)
            if request_path is None:
                continue
            index[self._normalize_request_path(request_path)].append(
                (name, method)
            )

        result = dict(index)
        self._method_index_cache[cache_key] = result
        return result

    @classmethod
    def _request_path_from_method(cls, method: Any) -> str | None:
        try:
            source = inspect.getsource(method)
        except (OSError, TypeError):
            return None
        match = cls._REQUEST_RE.search(source)
        return match.group(1) if match else None

    @staticmethod
    def _normalize_request_path(path: str) -> str:
        parts = [
            part
            for part in path.strip().split("/")
            if part and not (part.startswith("{") and part.endswith("}"))
        ]
        return "/" + "/".join(parts).casefold()

    @staticmethod
    def _method_key(method_name: str) -> str:
        if method_name.startswith("get_"):
            method_name = method_name[4:]
        return re.sub(r"[^0-9a-z]+", "", method_name.casefold())

    @staticmethod
    def _unique_methods(
        items: Sequence[tuple[str, Any]],
    ) -> list[tuple[str, Any]]:
        result: dict[str, Any] = {}
        for name, method in items:
            result[name] = method
        return list(result.items())

    @staticmethod
    def _call_signature(method: Any) -> dict[str, inspect.Parameter]:
        signature = inspect.signature(method)
        return {
            name: parameter
            for name, parameter in signature.parameters.items()
            if name != "self"
        }

    def _align_parameters(
        self,
        tag: str,
        wrapper_method: str,
        openapi_parameters: Sequence[ParameterIR],
        wrapper_parameters: Mapping[str, inspect.Parameter],
    ) -> WrapperEndpointSupport:
        remaining = list(openapi_parameters)
        aligned: list[ParameterIR] = []
        notes: list[str] = []

        for wrapper_name, wrapper_parameter in wrapper_parameters.items():
            api_name = str(self._parameter_map.get(wrapper_name, wrapper_name))
            match = self._match_parameter(
                tag,
                wrapper_name,
                api_name,
                remaining,
            )
            if match is None:
                if wrapper_parameter.default is not inspect.Parameter.empty:
                    notes.append(
                        f"{tag}.{wrapper_method}: wrapper parameter {wrapper_name!r} "
                        "is not represented by the current OpenAPI operation and was omitted"
                    )
                    continue
                raise WrapperUnsupported(
                    f"required TornAPIWrapper parameter {wrapper_name!r} cannot be mapped "
                    f"to the OpenAPI parameters for {tag}.{wrapper_method}"
                )

            remaining.remove(match)
            default = match.default
            if wrapper_parameter.default is inspect.Parameter.empty:
                default = MISSING
            else:
                default = wrapper_parameter.default

            type_ref = match.type_ref
            required = wrapper_parameter.default is inspect.Parameter.empty
            if not required and default is None:
                type_ref = type_ref.optional()

            aligned.append(
                replace(
                    match,
                    python_name=wrapper_name,
                    type_ref=type_ref,
                    required=required,
                    default=default,
                )
            )

        for parameter in remaining:
            if parameter.required:
                raise WrapperUnsupported(
                    f"TornAPIWrapper {wrapper_method}() does not expose required API "
                    f"parameter {parameter.wire_name!r}"
                )
            notes.append(
                f"{tag}.{wrapper_method}: optional API parameter {parameter.wire_name!r} "
                "is not supported by TornAPIWrapper and was omitted"
            )

        return WrapperEndpointSupport(
            wrapper_method,
            tuple(aligned),
            tuple(notes),
        )

    def _match_parameter(
        self,
        tag: str,
        wrapper_name: str,
        api_name: str,
        candidates: Sequence[ParameterIR],
    ) -> ParameterIR | None:
        exact_python = [p for p in candidates if p.python_name == wrapper_name]
        if len(exact_python) == 1:
            return exact_python[0]

        exact_api = [
            p
            for p in candidates
            if PythonNames.snake(p.wire_name) == PythonNames.snake(api_name)
        ]
        if len(exact_api) == 1:
            return exact_api[0]

        # One path identifier + one wrapper id-ish parameter is a safe mapping.
        # This covers names such as shopId -> shop_id even when an older
        # TornAPIWrapper parameter_map has not yet learned the new name.
        if api_name in {"id", "ids"} or wrapper_name.endswith(("_id", "_ids")):
            path_params = [p for p in candidates if p.location == "path"]
            if len(path_params) == 1:
                return path_params[0]

        return None


class ResponsePlanner:
    """Plan response extraction and generated Pydantic model surfaces."""

    def __init__(self, refs: RefResolver, overrides: TornOverrides) -> None:
        self.refs = refs
        self.overrides = overrides

    def plan(
        self, tag: str, selection: str, raw_ops: Sequence[RawOperation]
    ) -> ResponsePlan:
        """Plan response extraction and model naming for an endpoint.

        Args:
            tag: Resource tag that owns the endpoint.
            selection: Derived endpoint selection.
            raw_ops: OpenAPI operations represented by the endpoint.

        Returns:
            Response model and extraction strategy.

        Raises:
            MergeConflict: If response variants cannot share extraction.
            ReviewRequired: If no safe JSON response strategy exists.
        """
        schemas = [self._success_schema(op) for op in raw_ops]
        resolved_schemas: list[Mapping[str, Any]] = []
        for schema in schemas:
            resolved = self.refs.resolve(schema)
            if not isinstance(resolved, dict):
                raise ReviewRequired(
                    f"Invalid response schema for {tag}.{selection}"
                )
            resolved_schemas.append(resolved)

        fingerprints = {
            json.dumps(schema, sort_keys=True, separators=(",", ":"))
            for schema in schemas
        }
        if len(fingerprints) != 1:
            return self._plan_variant_response(
                tag,
                selection,
                schemas,
                resolved_schemas,
            )

        source = schemas[0]
        response_component = self.refs.ref_name(source)
        resolved = resolved_schemas[0]
        override = self.overrides.endpoint(tag, selection)
        extraction = self._extraction_for_schema(override, resolved)

        model_schema: Mapping[str, Any] = resolved
        model_source_component = response_component

        if extraction.kind == "key":
            property_schema = self._extract_property_schema(
                tag, selection, resolved, extraction.key
            )
            model_schema = property_schema
            model_source_component = self.refs.ref_name(property_schema)

        public_name = (
            override.response_model
            or self._default_public_model_name(
                tag,
                selection,
                response_component,
                model_source_component,
                model_schema,
            )
        )

        return ResponsePlan(
            response_component=response_component,
            source_schema=resolved,
            model_schema=model_schema,
            model_source_component=model_source_component,
            public_model_name=public_name,
            extraction=extraction,
        )

    def _plan_variant_response(
        self,
        tag: str,
        selection: str,
        source_schemas: Sequence[Mapping[str, Any]],
        resolved_schemas: Sequence[Mapping[str, Any]],
    ) -> ResponsePlan:
        override = self.overrides.endpoint(tag, selection)
        extractions = [
            self._extraction_for_schema(override, schema)
            for schema in resolved_schemas
        ]
        extraction_signatures = {
            (item.kind, item.key, item.extractor) for item in extractions
        }
        if len(extraction_signatures) != 1:
            raise MergeConflict(
                f"Response variants for {tag}.{selection} require different extraction "
                "strategies; add an endpoint override"
            )
        extraction = extractions[0]

        model_branches: list[Mapping[str, Any]] = []
        if extraction.kind == "key":
            for resolved in resolved_schemas:
                model_branches.append(
                    self._extract_property_schema(
                        tag, selection, resolved, extraction.key
                    )
                )
        else:
            model_branches.extend(resolved_schemas)

        # Different path variants can legitimately return different shapes while
        # being serviced by one TornAPIWrapper method. Preserve the public method
        # and express the payload as a precise Pydantic union instead of skipping.
        model_schema: Mapping[str, Any] = {"oneOf": model_branches}
        source_schema: Mapping[str, Any] = {"oneOf": list(resolved_schemas)}
        public_name = override.response_model or (
            f"{PythonNames.pascal(tag)}{PythonNames.pascal(selection)}Response"
        )

        return ResponsePlan(
            response_component=None,
            source_schema=source_schema,
            model_schema=model_schema,
            model_source_component=None,
            public_model_name=public_name,
            extraction=extraction,
        )

    def _extraction_for_schema(
        self,
        override: EndpointOverride,
        resolved: Mapping[str, Any],
    ) -> ExtractionIR:
        if override.custom_extractor:
            return ExtractionIR("custom", extractor=override.custom_extractor)
        if override.force_no_extract:
            return ExtractionIR("none")
        if override.extract:
            return ExtractionIR("key", key=override.extract)
        return self._infer_extraction(resolved)

    @staticmethod
    def _extract_property_schema(
        tag: str,
        selection: str,
        resolved: Mapping[str, Any],
        key: str | None,
    ) -> Mapping[str, Any]:
        properties = resolved.get("properties", {})
        if (
            key is None
            or not isinstance(properties, dict)
            or key not in properties
        ):
            raise ReviewRequired(
                f"Extraction key {key!r} does not exist in response for {tag}.{selection}"
            )
        property_schema = properties[key]
        if not isinstance(property_schema, dict):
            raise ReviewRequired(
                f"Invalid extracted schema for {tag}.{selection}"
            )
        return property_schema

    def _success_schema(self, raw: RawOperation) -> Mapping[str, Any]:
        responses = raw.operation.get("responses", {})
        for code in ("200", "201", "202", "default"):
            response = responses.get(code)
            if not isinstance(response, dict):
                continue
            response = self.refs.resolve(response)
            content = (
                response.get("content", {})
                if isinstance(response, dict)
                else {}
            )
            json_content = (
                content.get("application/json", {})
                if isinstance(content, dict)
                else {}
            )
            schema = (
                json_content.get("schema")
                if isinstance(json_content, dict)
                else None
            )
            if isinstance(schema, dict):
                return schema
        raise ReviewRequired(
            f"No supported JSON success response for {raw.http_method.upper()} {raw.path}"
        )

    @staticmethod
    def _infer_extraction(response_schema: Mapping[str, Any]) -> ExtractionIR:
        if (
            response_schema.get("type") != "object"
            and "properties" not in response_schema
        ):
            return ExtractionIR("none")
        properties = response_schema.get("properties", {})
        if isinstance(properties, dict) and len(properties) == 1:
            return ExtractionIR("key", key=next(iter(properties)))
        # Preserve multi-field responses, including payload + _metadata.
        return ExtractionIR("none")

    @staticmethod
    def _default_public_model_name(
        tag: str,
        selection: str,
        response_component: str | None,
        extracted_component: str | None,
        model_schema: Mapping[str, Any],
    ) -> str:
        if extracted_component:
            return extracted_component
        # Prefer Torn's own component name whenever it belongs to this tag. This
        # preserves intentional word boundaries that cannot be recovered from flat
        # path selections such as `forumfeed`, `territoryownership`, or
        # `rockpaperscissors`, including extracted root arrays.
        if response_component and response_component.startswith(
            PythonNames.pascal(tag)
        ):
            return response_component
        return (
            f"{PythonNames.pascal(tag)}{PythonNames.pascal(selection)}Response"
        )


class IRBuilder:
    """Build the normalized intermediate representation for SDK generation."""

    def __init__(
        self,
        discovery: EndpointDiscovery,
        parameters: ParameterNormalizer,
        responses: ResponsePlanner,
        overrides: TornOverrides,
        wrapper: TornAPIWrapperInspector,
        *,
        strict: bool = False,
    ) -> None:
        self.discovery = discovery
        self.parameters = parameters
        self.responses = responses
        self.overrides = overrides
        self.wrapper = wrapper
        self.strict = strict

    def build(self, selected_tags: set[str] | None = None) -> GenerationPlan:
        """Build the normalized SDK intermediate representation.

        Args:
            selected_tags: Optional normalized resource tags to include.

        Returns:
            Generated endpoint groups and non-fatal review warnings.

        Raises:
            MergeConflict: If operations cannot form one endpoint.
            ReviewRequired: If strict generation finds an unsafe endpoint.
        """
        raw = self.discovery.discover(selected_tags)
        grouped: dict[tuple[str, str], list[RawOperation]] = defaultdict(list)
        for operation in raw:
            override = self.overrides.endpoint(
                operation.tag, operation.selection
            )
            selection = PythonNames.snake(override.name or operation.selection)
            grouped[(operation.tag, selection)].append(
                replace(operation, selection=selection)
            )

        endpoints_by_tag: dict[str, list[EndpointIR]] = defaultdict(list)
        warnings: list[str] = []

        for (tag, selection), operations in sorted(grouped.items()):
            override = self.overrides.endpoint(tag, selection)
            if override.skip:
                continue
            http_methods = {op.http_method for op in operations}
            if len(http_methods) != 1:
                raise MergeConflict(
                    f"Multiple HTTP methods for {tag}.{selection}: {http_methods}"
                )
            if len(operations) > 1 and override.allow_merge is False:
                raise MergeConflict(f"Merge disabled for {tag}.{selection}")

            try:
                params = self.parameters.merge(tag, operations)
                preferred_wrapper_method = (
                    override.wrapper_method or f"get_{selection}"
                )
                wrapper_support = self.wrapper.inspect_endpoint(
                    tag,
                    preferred_wrapper_method,
                    params,
                    tuple(op.path for op in operations),
                )
                wrapper_method = wrapper_support.method_name
                params = wrapper_support.parameters
                warnings.extend(wrapper_support.notes)
                response = self.responses.plan(tag, selection, operations)
                stability_values = {
                    str(op.operation.get("x-stability"))
                    for op in operations
                    if op.operation.get("x-stability") is not None
                }
                stability = (
                    next(iter(stability_values))
                    if len(stability_values) == 1
                    else None
                )
                if len(stability_values) > 1:
                    warnings.append(
                        f"{tag}.{selection}: mixed x-stability values {sorted(stability_values)}"
                    )

                endpoints_by_tag[tag].append(
                    EndpointIR(
                        tag=tag,
                        name=selection,
                        source_paths=tuple(
                            sorted({op.path for op in operations})
                        ),
                        operation_ids=tuple(
                            sorted(
                                {
                                    op.operation_id
                                    for op in operations
                                    if op.operation_id
                                }
                            )
                        ),
                        parameters=params,
                        response=response,
                        wrapper_method=wrapper_method,
                        stability=stability,
                        documentation=self._documentation(operations),
                    )
                )
            except ReviewRequired as exc:
                if self.strict:
                    raise
                warnings.append(f"SKIPPED {tag}.{selection}: {exc}")

        tags = [
            TagIR(
                name=tag, endpoints=tuple(sorted(items, key=lambda e: e.name))
            )
            for tag, items in sorted(endpoints_by_tag.items())
        ]
        return GenerationPlan(tags=tags, warnings=warnings)

    @staticmethod
    def _documentation(operations: Sequence[RawOperation]) -> str | None:
        """Combine OpenAPI operation text for a generated endpoint docstring."""
        summaries = sorted(
            {
                str(operation.operation["summary"]).strip()
                for operation in operations
                if operation.operation.get("summary")
            }
        )
        descriptions = sorted(
            {
                str(operation.operation["description"]).strip()
                for operation in operations
                if operation.operation.get("description")
            }
        )
        sections = [" ".join(summaries), "\n\n".join(descriptions)]
        documentation = "\n\n".join(section for section in sections if section)
        return documentation or None


@dataclass
class ImportSet:
    """Collect imports required by a generated model module.

    Attributes:
        typing: Names imported from ``typing``.
        pydantic: Names imported from ``pydantic``.
        type_aliases: Generated type aliases imported by the module.
    """

    typing: set[str] = field(default_factory=set)
    pydantic: set[str] = field(default_factory=set)
    type_aliases: set[str] = field(default_factory=set)


class ModelRenderer:
    """Render OpenAPI response schemas as typed Pydantic model modules."""

    def __init__(
        self,
        document: OpenAPIDocument,
        refs: RefResolver,
        types: SchemaTypeResolver,
        overrides: TornOverrides,
    ) -> None:
        self.document = document
        self.refs = refs
        self.types = types
        self.overrides = overrides
        self._inline_models: dict[str, Mapping[str, Any]] = {}

    def render_endpoint_model(self, endpoint: EndpointIR) -> str:
        """Render the Pydantic model module for one generated endpoint.

        Args:
            endpoint: Normalized endpoint to render.

        Returns:
            Complete generated model module source.

        Raises:
            ReviewRequired: If the endpoint schema cannot be rendered safely.
        """
        imports = ImportSet()
        root_name = endpoint.response.public_model_name
        root_schema = endpoint.response.model_schema
        root_source = endpoint.response.model_source_component

        dependency_names = self._collect_model_dependencies(
            root_schema, skip_component=root_source
        )
        # If root is a direct component and public name equals that component, render
        # that component as the root rather than a duplicate dependency.
        if (
            root_source
            and root_source != root_name
            and self._needs_named_model(
                self.document.schemas.get(root_source, {})
            )
        ):
            dependency_names.discard(root_source)

        blocks: list[str] = []
        self._inline_models = {}

        # Pre-discover inline object/allOf models so fields can refer to concrete
        # generated class names without degrading to Any.
        for component_name in sorted(dependency_names):
            schema = self.document.schemas.get(component_name)
            if isinstance(schema, dict) and self._needs_named_model(schema):
                self._discover_inline_models(component_name, schema)

        resolved_root = self.refs.resolve(root_schema)
        if not isinstance(resolved_root, dict):
            raise ReviewRequired(
                f"Invalid root model schema for {endpoint.tag}.{endpoint.name}"
            )
        self._discover_inline_models(root_name, resolved_root)

        # Dependencies first. Normal field annotations are safe as forward
        # references because future annotations are enabled, but model names used
        # inside runtime-evaluated generic bases (RootModel[...] / TornListModel[...])
        # must already exist. Order those dependencies topologically instead of
        # alphabetically.
        for component_name in self._order_model_dependencies(dependency_names):
            schema = self.document.schemas.get(component_name)
            if not isinstance(schema, dict) or not self._needs_named_model(
                schema
            ):
                continue
            blocks.append(
                self._render_named_model(component_name, schema, imports)
            )

        for inline_name, inline_schema in sorted(self._inline_models.items()):
            if inline_name == root_name or inline_name in dependency_names:
                continue
            blocks.append(
                self._render_named_model(inline_name, inline_schema, imports)
            )

        blocks.append(
            self._render_named_model(
                root_name, resolved_root, imports, root=True
            )
        )

        return self._module(imports, blocks)

    def _discover_inline_models(
        self, parent_name: str, schema: Mapping[str, Any]
    ) -> None:
        schema = self._normalize_allof(schema)

        # A response may be extracted from a one-property wrapper, turning an
        # inline array property into the root schema. In that case there is no
        # parent object/property traversal to discover the array item model, so
        # discover it explicitly here.
        if schema.get("type") == "array":
            items = schema.get("items")
            if (
                isinstance(items, dict)
                and "$ref" not in items
                and (
                    "allOf" in items
                    or items.get("type") == "object"
                    or "properties" in items
                )
            ):
                child = f"{parent_name}Item"
                normalized = self._normalize_allof(items)
                self._inline_models.setdefault(child, normalized)
                self._discover_inline_models(child, normalized)
            return

        properties = schema.get("properties", {})
        if not isinstance(properties, dict):
            return
        for wire_name, field_schema in properties.items():
            if not isinstance(field_schema, dict) or "$ref" in field_schema:
                continue
            child_base = f"{parent_name}{PythonNames.pascal(wire_name)}"
            if (
                "allOf" in field_schema
                or field_schema.get("type") == "object"
                or "properties" in field_schema
            ):
                normalized = self._normalize_allof(field_schema)
                self._inline_models.setdefault(child_base, normalized)
                self._discover_inline_models(child_base, normalized)
                continue
            if field_schema.get("type") == "array":
                items = field_schema.get("items")
                if (
                    isinstance(items, dict)
                    and "$ref" not in items
                    and (
                        "allOf" in items
                        or items.get("type") == "object"
                        or "properties" in items
                    )
                ):
                    child = f"{child_base}Item"
                    normalized = self._normalize_allof(items)
                    self._inline_models.setdefault(child, normalized)
                    self._discover_inline_models(child, normalized)
            for union_key in ("oneOf", "anyOf"):
                branches = field_schema.get(union_key)
                if isinstance(branches, list):
                    for idx, branch in enumerate(branches, 1):
                        if (
                            isinstance(branch, dict)
                            and "$ref" not in branch
                            and (
                                "allOf" in branch
                                or branch.get("type") == "object"
                                or "properties" in branch
                            )
                        ):
                            child = f"{child_base}Variant{idx}"
                            normalized = self._normalize_allof(branch)
                            self._inline_models.setdefault(child, normalized)
                            self._discover_inline_models(child, normalized)

    def _field_type(
        self, model_name: str, wire_name: str, schema: Mapping[str, Any]
    ) -> TypeRef:
        child_base = f"{model_name}{PythonNames.pascal(wire_name)}"
        if "$ref" not in schema and (
            "allOf" in schema
            or schema.get("type") == "object"
            or "properties" in schema
        ):
            return TypeRef(child_base)
        if schema.get("type") == "array":
            items = schema.get("items")
            if (
                isinstance(items, dict)
                and "$ref" not in items
                and (
                    "allOf" in items
                    or items.get("type") == "object"
                    or "properties" in items
                )
            ):
                return TypeRef(f"list[{child_base}Item]")
        for union_key in ("oneOf", "anyOf"):
            branches = schema.get(union_key)
            if isinstance(branches, list):
                refs: list[TypeRef] = []
                for idx, branch in enumerate(branches, 1):
                    if (
                        isinstance(branch, dict)
                        and "$ref" not in branch
                        and (
                            "allOf" in branch
                            or branch.get("type") == "object"
                            or "properties" in branch
                        )
                    ):
                        refs.append(TypeRef(f"{child_base}Variant{idx}"))
                    else:
                        refs.append(
                            self.types.resolve_type(
                                branch, source_name=f"{child_base}Variant{idx}"
                            )
                        )
                return self.types._union(refs)
        source_name = self.refs.ref_name(schema) or child_base
        return self.types.resolve_type(schema, source_name=source_name)

    def _collect_model_dependencies(
        self,
        schema: Mapping[str, Any],
        *,
        skip_component: str | None = None,
    ) -> set[str]:
        result: set[str] = set()
        queue: deque[Any] = deque([schema])
        visited_refs: set[str] = set()
        while queue:
            node = queue.popleft()
            if not isinstance(node, dict):
                continue
            ref_name = self.refs.ref_name(node)
            if ref_name:
                if ref_name in visited_refs:
                    continue
                visited_refs.add(ref_name)
                target = self.document.schemas.get(ref_name)
                if not isinstance(target, dict):
                    continue
                if ref_name != skip_component and self._needs_named_model(
                    target
                ):
                    result.add(ref_name)
                queue.append(target)
                continue
            for key in ("properties",):
                value = node.get(key)
                if isinstance(value, dict):
                    queue.extend(value.values())
            for key in ("items", "additionalProperties"):
                value = node.get(key)
                if isinstance(value, dict):
                    queue.append(value)
            for key in ("oneOf", "anyOf", "allOf"):
                value = node.get(key)
                if isinstance(value, list):
                    queue.extend(value)
        return result

    def _order_model_dependencies(self, names: set[str]) -> list[str]:
        """Order generated component models by runtime base dependencies.

        ``from __future__ import annotations`` postpones field annotations, but it
        does not postpone expressions used in class bases. For example::

            class TradeItem(RootModel[TradeItemMoney | TradeItemItem]): ...

        requires ``TradeItemMoney`` and ``TradeItemItem`` to be defined first.
        The same applies to ``TornListModel[SomeModel]``.
        """
        available = set(names)
        graph: dict[str, set[str]] = {}

        for name in names:
            schema = self.document.schemas.get(name)
            if not isinstance(schema, dict):
                graph[name] = set()
                continue
            graph[name] = self._runtime_model_dependencies(schema) & available
            graph[name].discard(name)

        ordered: list[str] = []
        temporary: set[str] = set()
        permanent: set[str] = set()

        def visit(name: str) -> None:
            if name in permanent:
                return
            if name in temporary:
                cycle = " -> ".join(sorted(temporary | {name}))
                raise ReviewRequired(
                    f"Runtime model dependency cycle requires an override: {cycle}"
                )

            temporary.add(name)
            for dependency in sorted(graph.get(name, ())):
                visit(dependency)
            temporary.remove(name)
            permanent.add(name)
            ordered.append(name)

        for name in sorted(names):
            visit(name)

        return ordered

    def _runtime_model_dependencies(
        self, schema: Mapping[str, Any]
    ) -> set[str]:
        """Return model refs evaluated while constructing a class base.

        Object field annotations do not count: they are postponed by future
        annotations. Only root unions/scalars and root arrays are relevant here.
        """
        schema = self._normalize_allof(schema)

        if "oneOf" in schema or "anyOf" in schema:
            branches = schema.get("oneOf") or schema.get("anyOf") or []
            return self._collect_refs_from_type_schema(branches)

        if schema.get("type") == "array":
            items = schema.get("items")
            if isinstance(items, dict):
                return self._collect_refs_from_type_schema(items)

        return set()

    def _collect_refs_from_type_schema(self, node: Any) -> set[str]:
        refs: set[str] = set()
        queue: deque[Any] = deque([node])

        while queue:
            current = queue.popleft()
            if isinstance(current, list):
                queue.extend(current)
                continue
            if not isinstance(current, dict):
                continue

            ref_name = self.refs.ref_name(current)
            if ref_name:
                refs.add(ref_name)
                continue

            for key in ("items", "additionalProperties"):
                value = current.get(key)
                if isinstance(value, dict):
                    queue.append(value)

            for key in ("oneOf", "anyOf", "allOf"):
                value = current.get(key)
                if isinstance(value, list):
                    queue.extend(value)

        return refs

    def _render_named_model(
        self,
        name: str,
        schema: Mapping[str, Any],
        imports: ImportSet,
        *,
        root: bool = False,
    ) -> str:
        schema = self._normalize_allof(schema)
        if "enum" in schema or self.types._is_scalar_like(schema):
            # Endpoint roots must remain Pydantic models because decorators expect
            # BaseModel returns. Dependencies that are scalar are normally inlined.
            type_ref = self.types.resolve_type(schema, source_name=name)
            imports.type_aliases.update(type_ref.aliases)
            imports.pydantic.add("RootModel")
            return self._root_model(
                name, f"RootModel[{type_ref.code}]", schema
            )

        if "oneOf" in schema or "anyOf" in schema:
            type_ref = self.types.resolve_type(schema, source_name=name)
            imports.type_aliases.update(type_ref.aliases)
            imports.pydantic.add("RootModel")
            return self._root_model(
                name, f"RootModel[{type_ref.code}]", schema
            )

        schema_type = schema.get("type")
        if schema_type == "array":
            items = schema.get("items")
            if not isinstance(items, dict):
                raise ReviewRequired(f"Array model {name} has no items")
            item_type = self.types.resolve_type(
                items, source_name=f"{name}Item"
            )
            imports.type_aliases.update(item_type.aliases)
            if self._item_is_torn_model(items):
                return self._root_model(
                    name, f"TornListModel[{item_type.code}]", schema
                )
            imports.pydantic.add("RootModel")
            return self._root_model(
                name, f"RootModel[list[{item_type.code}]]", schema
            )

        if schema_type == "object" or "properties" in schema:
            return self._render_object(name, schema, imports)

        raise ReviewRequired(f"Cannot render model {name}: {schema!r}")

    def _root_model(
        self, name: str, base: str, schema: Mapping[str, Any]
    ) -> str:
        """Render a scalar, union, or list response model with documentation."""
        lines = [f"class {name}({base}):"]
        lines.extend(self._docstring_lines(name, schema))
        lines.extend(custom_block("class", name=name, indent="    "))
        return "\n".join(lines) + "\n"

    @staticmethod
    def _model_docstring(name: str, schema: Mapping[str, Any]) -> str:
        """Use OpenAPI schema text, with a useful fallback for anonymous schemas."""
        description = str(schema.get("description", "")).strip()
        return (
            description or f"Pydantic model for the {name} Torn API response."
        )

    def _docstring_lines(
        self,
        name: str,
        schema: Mapping[str, Any],
        *,
        attributes: Sequence[str] = (),
    ) -> list[str]:
        """Render OpenAPI schema documentation as a safe class docstring."""
        documentation = self._model_docstring(name, schema)
        escaped = documentation.replace("\\", "\\\\").replace('"""', '\\"""')
        body = [
            f"    {line}" if line else "    " for line in escaped.splitlines()
        ]
        lines = ['    """', *body]
        if attributes:
            lines.extend(["", "    Attributes:", *attributes])
        lines.append('    """')
        return lines

    def _render_object(
        self, name: str, schema: Mapping[str, Any], imports: ImportSet
    ) -> str:
        properties = schema.get("properties", {})
        required = set(schema.get("required", []) or [])
        if not isinstance(properties, dict):
            raise ReviewRequired(f"Model {name} has invalid properties")
        attributes: list[str] = []
        if properties:
            for wire_name, field_schema in properties.items():
                if not isinstance(field_schema, dict):
                    continue
                py_name, _ = PythonNames.identifier(wire_name)
                type_ref = self._field_type(name, wire_name, field_schema)
                imports.type_aliases.update(type_ref.aliases)
                description = str(field_schema.get("description", "")).strip()
                attributes.append(
                    f"        {py_name} ({type_ref.code}): "
                    f"{description or f'Torn API field `{wire_name}`.'}"
                )
        lines = [f"class {name}(TornModel):"]
        lines.extend(
            self._docstring_lines(name, schema, attributes=attributes)
        )
        lines.extend(custom_block("class", name=name, indent="    "))
        if not properties:
            lines.append("    pass")
            return "\n".join(lines) + "\n"

        for wire_name, field_schema in properties.items():
            if not isinstance(field_schema, dict):
                continue
            override = self.overrides.field(name, wire_name)
            py_name, automatic_alias = PythonNames.identifier(wire_name)
            if override and override.python_name:
                py_name = override.python_name

            if override and override.python_type:
                type_ref = TypeRef(override.python_type)
            else:
                type_ref = self._field_type(name, wire_name, field_schema)
            imports.type_aliases.update(type_ref.aliases)

            is_required = wire_name in required
            default = MISSING
            if override and override.default is not MISSING:
                default = override.default
            elif "default" in field_schema:
                default = field_schema["default"]
            elif not is_required:
                default = None
                type_ref = type_ref.optional()

            aliases = override.aliases if override and override.aliases else ()
            alias_expr: str | None = None
            if aliases:
                imports.pydantic.update({"AliasChoices", "Field"})
                joined = ", ".join(repr(v) for v in aliases)
                alias_expr = f"Field(validation_alias=AliasChoices({joined}))"
            elif automatic_alias:
                imports.pydantic.add("Field")
                alias_expr = f"Field(alias={wire_name!r})"

            if alias_expr and default is not MISSING and default is not None:
                # Field(default=..., alias=...) would be more complete, but aliases
                # with non-None defaults are rare; render explicitly when needed.
                imports.pydantic.add("Field")
                if aliases:
                    joined = ", ".join(repr(v) for v in aliases)
                    alias_expr = (
                        f"Field(default={self._default(default)}, "
                        f"validation_alias=AliasChoices({joined}))"
                    )
                else:
                    alias_expr = f"Field(default={self._default(default)}, alias={wire_name!r})"
            elif alias_expr and default is None:
                if aliases:
                    joined = ", ".join(repr(v) for v in aliases)
                    alias_expr = (
                        "Field(default=None, validation_alias="
                        f"AliasChoices({joined}))"
                    )
                else:
                    alias_expr = f"Field(default=None, alias={wire_name!r})"

            if alias_expr:
                lines.append(f"    {py_name}: {type_ref.code} = {alias_expr}")
            elif default is MISSING:
                lines.append(f"    {py_name}: {type_ref.code}")
            else:
                lines.append(
                    f"    {py_name}: {type_ref.code} = {self._default(default)}"
                )

        return "\n".join(lines) + "\n"

    def _normalize_allof(self, schema: Mapping[str, Any]) -> Mapping[str, Any]:
        if "allOf" not in schema:
            return schema
        merged: dict[str, Any] = {
            k: v for k, v in schema.items() if k != "allOf"
        }
        properties: dict[str, Any] = dict(merged.get("properties", {}) or {})
        required: list[str] = list(merged.get("required", []) or [])
        for branch in schema.get("allOf", []) or []:
            if not isinstance(branch, dict):
                continue
            resolved = self.refs.resolve(branch)
            if not isinstance(resolved, dict):
                continue
            resolved = self._normalize_allof(resolved)
            properties.update(resolved.get("properties", {}) or {})
            for item in resolved.get("required", []) or []:
                if item not in required:
                    required.append(item)
        merged["type"] = "object"
        merged["properties"] = properties
        if required:
            merged["required"] = required
        return merged

    def _item_is_torn_model(self, schema: Mapping[str, Any]) -> bool:
        ref_name = self.refs.ref_name(schema)
        if ref_name:
            target = self.document.schemas.get(ref_name)
            return isinstance(target, dict) and self._needs_named_model(target)
        resolved = self.refs.resolve(schema)
        return isinstance(resolved, dict) and (
            resolved.get("type") == "object" or "properties" in resolved
        )

    def _needs_named_model(self, schema: Mapping[str, Any]) -> bool:
        schema = self._normalize_allof(schema)
        if "enum" in schema or self.types._is_scalar_like(schema):
            return False
        if "oneOf" in schema or "anyOf" in schema:
            return True
        schema_type = schema.get("type")
        return schema_type in {"object", "array"} or "properties" in schema

    def _module(self, imports: ImportSet, blocks: Sequence[str]) -> str:
        lines = generated_module_header(
            "Pydantic response models generated from the Torn OpenAPI specification."
        )
        pydantic_imports = set(imports.pydantic)
        # Base model import is always needed for object/list rendering; importing
        # both is harmless and keeps generated modules deterministic/simple.
        lines.append(
            "from torn_sdk.models.base import TornListModel, TornModel"
        )
        if pydantic_imports:
            lines.append(
                f"from pydantic import {', '.join(sorted(pydantic_imports))}"
            )
        if imports.type_aliases:
            lines.append(
                "from torn_sdk.models.types import "
                + ", ".join(sorted(imports.type_aliases))
            )
        lines.append("")
        lines.append("\n\n".join(block.rstrip() for block in blocks))
        return "\n".join(lines).rstrip() + "\n"

    @staticmethod
    def _default(value: Any) -> str:
        return repr(value)


