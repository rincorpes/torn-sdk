"""One-file OpenAPI -> Torn SDK code generator.

The generator intentionally favors explicit generated Python over runtime magic so
IDE autocomplete and static type checking remain first-class.

Typical usage:
    python torn_sdk_codegen.py openapi.json --sdk-root src/torn_sdk --tag User
    python torn_sdk_codegen.py openapi.json --sdk-root src/torn_sdk --check

Generated surfaces:
    models/types.py
    models/<tag>/<selection>.py
    models/<tag>/__init__.py
    resources/_generated/<tag>.py
    resources/_generated/<tag>_async.py
    resources/__init__.py
    client.py
    client_async.py

Optional create-only scaffolds:
    resources/<tag>.py
    resources/<tag>_async.py

Handwritten infrastructure (base models, decorators, parser, registries,
raw namespaces, overrides/custom extractors) remains outside generator ownership.
"""

