class PlanBuilder:
    def __init__(
        self,
        discovery: EndpointDiscovery,
        parameters: ParameterPlanner,
        wrapper: TornAPIWrapperInspector,
        responses: ResponsePlanner,
        *,
        strict: bool,
    ) -> None:
        self.discovery = discovery
        self.parameters = parameters
        self.wrapper = wrapper
        self.responses = responses
        self.strict = strict

    def build(
        self,
        selected_tags: set[str] | None,
    ) -> GenerationPlan:
        raw = self.discovery.discover(selected_tags)

        groups: dict[
            tuple[str, str],
            list[RawOperation],
        ] = defaultdict(list)

        for operation in raw:
            groups[
                (
                    operation.tag,
                    operation.selection,
                )
            ].append(operation)

        by_tag: dict[str, list[MockRoute]] = defaultdict(list)
        warnings: list[str] = []

        for (tag, selection), operations in sorted(groups.items()):
            try:
                route, notes = self._route(
                    tag,
                    selection,
                    operations,
                )
            except ReviewRequired as exc:
                if self.strict:
                    raise

                warnings.append(f"SKIPPED {tag}.{selection}: {exc}")
                continue

            by_tag[tag].append(route)
            warnings.extend(notes)

        tags = [
            TagSpec(
                name=tag,
                routes=tuple(
                    sorted(
                        routes,
                        key=lambda item: item.selection,
                    )
                ),
            )
            for tag, routes in sorted(by_tag.items())
        ]

        return GenerationPlan(
            tags=tags,
            warnings=warnings,
        )

    def _route(
        self,
        tag: str,
        selection: str,
        operations: Sequence[RawOperation],
    ) -> tuple[MockRoute, list[str]]:
        if len({operation.http_method for operation in operations}) != 1:
            raise ReviewRequired(
                f"multiple HTTP methods for " f"{tag}.{selection}"
            )

        preferred_method = f"get_{selection}"
        params = self.parameters.merged_parameters(operations)

        fallback_request_path = self._request_path(operations)
        wrapper = self.wrapper.inspect_endpoint(
            tag,
            preferred_method,
            params,
            tuple(operation.path for operation in operations),
            fallback_request_path,
        )
        method_name = wrapper.method_name
        request_path = wrapper.request_path
        route_notes = list(wrapper.notes)

        path_request_names = {
            param.api_name: wrapper.request_parameter_names[param.api_name]
            for param in params
            if (
                param.location == "path"
                and param.api_name in wrapper.request_parameter_names
            )
        }

        all_path_keys = set(path_request_names.values())

        variants: list[RouteVariant] = []

        for operation in operations:
            op_params = self.parameters.operation_parameters(operation)

            required_api_path_params = {
                param.api_name
                for param in op_params
                if param.location == "path"
            }

            required = tuple(
                sorted(
                    path_request_names[name]
                    for name in required_api_path_params
                    if name in path_request_names
                )
            )

            # If this route requires a path parameter but the wrapper cannot
            # expose it, the wrapper cannot faithfully invoke this variant.
            if required_api_path_params and len(required) != len(
                required_api_path_params
            ):
                missing = sorted(
                    required_api_path_params - set(path_request_names)
                )
                route_notes.append(
                    f"{tag}.{method_name}: skipped OpenAPI variant {operation.path}: "
                    f"wrapper cannot map path parameter(s) {missing}"
                )
                continue

            forbidden = tuple(sorted(all_path_keys - set(required)))

            variants.append(
                RouteVariant(
                    source_path=operation.path,
                    required_params=required,
                    forbidden_params=forbidden,
                    response=self.responses.example(operation),
                )
            )

        if not variants:
            raise WrapperUnsupported(
                f"{method_name}() cannot service any OpenAPI route variant"
            )

        variants.sort(
            key=lambda item: (
                len(item.required_params),
                item.source_path,
            )
        )

        return (
            MockRoute(
                tag=tag,
                selection=selection,
                wrapper_method=method_name,
                request_path=request_path,
                variants=tuple(variants),
            ),
            route_notes,
        )

    @staticmethod
    def _request_path(
        operations: Sequence[RawOperation],
    ) -> str:
        candidates: list[tuple[int, str]] = []

        for operation in operations:
            parts = [
                part for part in operation.path.strip("/").split("/") if part
            ]

            static = [
                part
                for part in parts
                if not (part.startswith("{") and part.endswith("}"))
            ]

            candidate = "/" + "/".join(static)
            dynamic_count = len(parts) - len(static)

            candidates.append(
                (
                    dynamic_count,
                    candidate,
                )
            )

        # Prefer the concrete/self route if available.
        return sorted(candidates)[0][1]


