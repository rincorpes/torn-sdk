class ResponsePlanner:
    def __init__(
        self,
        refs: RefResolver,
        examples: SchemaExampleFactory,
    ) -> None:
        self.refs = refs
        self.examples = examples

    def example(
        self,
        raw: RawOperation,
    ) -> Any:
        schema = self._json_schema(raw)

        return self.examples.build(
            schema,
            name_hint=(f"{raw.tag}_" f"{raw.selection}_response"),
        )

    def _json_schema(
        self,
        raw: RawOperation,
    ) -> Mapping[str, Any]:
        responses = raw.operation.get("responses", {})

        if not isinstance(responses, Mapping):
            raise ReviewRequired(
                f"no responses for " f"{raw.http_method.upper()} {raw.path}"
            )

        successes: list[tuple[str, Mapping[str, Any]]] = []

        for status, value in responses.items():
            if not str(status).startswith("2"):
                continue

            resolved = self.refs.resolve(value)

            if isinstance(resolved, Mapping):
                successes.append((str(status), resolved))

        for _, response in sorted(successes):
            content = response.get("content", {})

            if not isinstance(content, Mapping):
                continue

            media = content.get("application/json")

            if not isinstance(media, Mapping):
                media = next(
                    (
                        value
                        for key, value in content.items()
                        if (
                            str(key).endswith("+json")
                            and isinstance(value, Mapping)
                        )
                    ),
                    None,
                )

            if not isinstance(media, Mapping):
                continue

            schema = media.get("schema")

            if isinstance(schema, Mapping):
                return schema

        raise ReviewRequired(
            f"no supported JSON success response for "
            f"{raw.http_method.upper()} {raw.path}"
        )


