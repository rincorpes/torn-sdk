class ParameterPlanner:
    def __init__(self, document: OpenAPIDocument, refs: RefResolver) -> None:
        self.document = document
        self.refs = refs

    def operation_parameters(
        self,
        raw: RawOperation,
    ) -> list[ParameterSpec]:
        path_item = self.document.paths.get(raw.path, {})
        inputs: list[Any] = []

        if isinstance(path_item, Mapping):
            path_parameters = path_item.get("parameters", [])
            if isinstance(path_parameters, list):
                inputs.extend(path_parameters)

        operation_parameters = raw.operation.get("parameters", [])
        if isinstance(operation_parameters, list):
            inputs.extend(operation_parameters)

        output: dict[tuple[str, str], ParameterSpec] = {}

        for item in inputs:
            resolved = self.refs.resolve(item)

            if not isinstance(resolved, Mapping):
                continue

            location = str(resolved.get("in", ""))

            if location not in {"path", "query"}:
                continue

            name = str(resolved.get("name", ""))

            if not name:
                continue

            if name.lower() in {"key", "api_key", "apikey"}:
                continue

            if location == "path" and name == "id":
                python_name = f"{raw.tag}_id"
            else:
                python_name, _ = PythonNames.identifier(name)

            output[(name, location)] = ParameterSpec(
                api_name=name,
                python_name=python_name,
                location=location,
                required=bool(
                    resolved.get(
                        "required",
                        location == "path",
                    )
                ),
            )

        return list(output.values())

    def merged_parameters(
        self,
        operations: Sequence[RawOperation],
    ) -> list[ParameterSpec]:
        merged: dict[tuple[str, str], ParameterSpec] = {}
        counts: dict[tuple[str, str], int] = defaultdict(int)

        for raw in operations:
            seen: set[tuple[str, str]] = set()

            for param in self.operation_parameters(raw):
                key = (param.api_name, param.location)
                merged.setdefault(key, param)

                if key not in seen:
                    counts[key] += 1
                    seen.add(key)

        total = len(operations)
        output: list[ParameterSpec] = []

        for key, param in merged.items():
            output.append(
                ParameterSpec(
                    api_name=param.api_name,
                    python_name=param.python_name,
                    location=param.location,
                    required=(param.required and counts[key] == total),
                )
            )

        return output


