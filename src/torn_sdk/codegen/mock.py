class ModuleRenderer:
    def render(
        self,
        plan: GenerationPlan,
        *,
        openapi_version: str,
        openapi_hash: str,
    ) -> str:
        lines: list[str] = [
            GENERATED_HEADER,
            "from __future__ import annotations",
            "",
            "from copy import deepcopy",
            "from dataclasses import dataclass",
            "from typing import Any, Callable",
            "",
            "from TornAPIWrapper import (",
            "    TornAPIWrapper,",
            "    TornAPIWrapperAsync,",
            ")",
        ]

        for tag in plan.tags:
            cls = PythonNames.pascal(tag.name)

            lines.extend(
                [
                    f"from TornAPIWrapper.endpoints.{tag.name} "
                    f"import {cls} as Sync{cls}",
                    f"from TornAPIWrapper.endpoints_async.{tag.name} "
                    f"import {cls} as Async{cls}",
                ]
            )

        lines.extend(
            [
                "",
                f"OPENAPI_VERSION = {openapi_version!r}",
                f"OPENAPI_SHA256 = {openapi_hash!r}",
                "",
            ]
        )

        lines.extend(self._runtime_support())
        lines.append("")
        lines.extend(self._routes(plan))
        lines.append("")
        lines.extend(
            self._client(
                plan.tags,
                async_=False,
            )
        )
        lines.append("")
        lines.extend(
            self._client(
                plan.tags,
                async_=True,
            )
        )
        lines.extend(
            [
                "",
                "__all__ = [",
                '    "MockRequest",',
                '    "MockController",',
                '    "MockTornAPIWrapper",',
                '    "MockTornAPIWrapperAsync",',
                "]",
                "",
            ]
        )

        return "\n".join(lines)

    @staticmethod
    def _runtime_support() -> list[str]:
        return [
            "@dataclass(frozen=True)",
            "class MockRequest:",
            "    endpoint: str",
            "    params: dict[str, Any]",
            "",
            "",
            "@dataclass(frozen=True)",
            "class _RouteVariant:",
            "    required: tuple[str, ...]",
            "    forbidden: tuple[str, ...]",
            "    response: Any",
            "",
            "",
            "ResponseOverride = Any | Callable[[dict[str, Any]], Any]",
            "",
            "",
            "class MockController:",
            "    def __init__(self) -> None:",
            "        self.calls: list[MockRequest] = []",
            "        self._responses: dict[str, ResponseOverride] = {}",
            "        self._errors: dict[str, BaseException | type[BaseException]] = {}",
            "",
            "    @staticmethod",
            "    def _normalize_endpoint(endpoint: str) -> str:",
            "        endpoint = endpoint.strip()",
            "        if not endpoint.startswith('/'):",
            "            if '.' in endpoint:",
            "                endpoint = '/' + endpoint.replace('.', '/')",
            "            else:",
            "                endpoint = '/' + endpoint",
            "        return endpoint.rstrip('/') or '/'",
            "",
            "    def set_response(",
            "        self,",
            "        endpoint: str,",
            "        response: ResponseOverride,",
            "    ) -> None:",
            "        self._responses[self._normalize_endpoint(endpoint)] = response",
            "",
            "    def set_error(",
            "        self,",
            "        endpoint: str,",
            "        error: BaseException | type[BaseException],",
            "    ) -> None:",
            "        self._errors[self._normalize_endpoint(endpoint)] = error",
            "",
            "    def clear_response(self, endpoint: str) -> None:",
            "        self._responses.pop(self._normalize_endpoint(endpoint), None)",
            "",
            "    def clear_error(self, endpoint: str) -> None:",
            "        self._errors.pop(self._normalize_endpoint(endpoint), None)",
            "",
            "    def reset(self) -> None:",
            "        self.calls.clear()",
            "        self._responses.clear()",
            "        self._errors.clear()",
            "",
            "    def last_call(self, endpoint: str | None = None) -> MockRequest | None:",
            "        normalized = (",
            "            self._normalize_endpoint(endpoint)",
            "            if endpoint is not None",
            "            else None",
            "        )",
            "        for call in reversed(self.calls):",
            "            if normalized is None or call.endpoint == normalized:",
            "                return call",
            "        return None",
            "",
            "    def request(",
            "        self,",
            "        endpoint: str,",
            "        params: dict[str, Any] | None,",
            "    ) -> Any:",
            "        endpoint = self._normalize_endpoint(endpoint)",
            "        params = dict(params or {})",
            "        self.calls.append(MockRequest(endpoint=endpoint, params=params))",
            "",
            "        error = self._errors.get(endpoint)",
            "        if error is not None:",
            "            if isinstance(error, type) and issubclass(error, BaseException):",
            "                raise error()",
            "            raise error",
            "",
            "        if endpoint in self._responses:",
            "            override = self._responses[endpoint]",
            "            if callable(override):",
            "                return override(dict(params))",
            "            return deepcopy(override)",
            "",
            "        variants = _ROUTES.get(endpoint)",
            "        if variants is None:",
            "            raise LookupError(f'No OpenAPI mock route for {endpoint}')",
            "",
            "        for variant in variants:",
            "            if any(params.get(name) is None for name in variant.required):",
            "                continue",
            "            if any(params.get(name) is not None for name in variant.forbidden):",
            "                continue",
            "            return deepcopy(variant.response)",
            "",
            "        return deepcopy(variants[0].response)",
        ]

    @staticmethod
    def _routes(
        plan: GenerationPlan,
    ) -> list[str]:
        lines = ["_ROUTES: dict[str, tuple[_RouteVariant, ...]] = {"]

        for tag in plan.tags:
            for route in tag.routes:
                lines.append(f"    {route.request_path!r}: (")

                for variant in route.variants:
                    lines.append("        _RouteVariant(")
                    lines.append(
                        f"            required={variant.required_params!r},"
                    )
                    lines.append(
                        f"            forbidden={variant.forbidden_params!r},"
                    )
                    lines.append(f"            response={variant.response!r},")
                    lines.append("        ),")

                lines.append("    ),")

        lines.append("}")
        return lines

    @staticmethod
    def _client(
        tags: Sequence[TagSpec],
        *,
        async_: bool,
    ) -> list[str]:
        name = "MockTornAPIWrapperAsync" if async_ else "MockTornAPIWrapper"
        parent = "TornAPIWrapperAsync" if async_ else "TornAPIWrapper"

        lines = [
            f"class {name}({parent}):",
            "    def __init__(",
            "        self,",
            "        api_key: str = 'mock-api-key',",
            "        request_timeout: float | tuple[float, float] = 10,",
            "        *,",
            "        controller: MockController | None = None,",
            "    ) -> None:",
            "        # Deliberately do not call TornAPIWrapper.__init__.",
            "        # That prevents creation of requests/aiohttp sessions.",
            "        self.api_key = api_key",
            "        self.request_timeout = request_timeout",
            "        self._mock = controller or MockController()",
        ]

        for tag in tags:
            cls = PythonNames.pascal(tag.name)
            prefix = "Async" if async_ else "Sync"

            lines.append(f"        self.{tag.name} = {prefix}{cls}(self)")

        lines.extend(
            [
                "",
                "    @property",
                "    def calls(self) -> list[MockRequest]:",
                "        return self._mock.calls",
                "",
                "    def set_response(",
                "        self,",
                "        endpoint: str,",
                "        response: ResponseOverride,",
                "    ) -> None:",
                "        self._mock.set_response(endpoint, response)",
                "",
                "    def set_error(",
                "        self,",
                "        endpoint: str,",
                "        error: BaseException | type[BaseException],",
                "    ) -> None:",
                "        self._mock.set_error(endpoint, error)",
                "",
                "    def reset(self) -> None:",
                "        self._mock.reset()",
            ]
        )

        if async_:
            lines.extend(
                [
                    "",
                    "    async def request(",
                    "        self,",
                    "        endpoint: str,",
                    "        params: dict | None,",
                    "    ) -> dict | str:",
                    "        return self._mock.request(endpoint, params)",
                    "",
                    "    async def close(self) -> None:",
                    "        return None",
                    "",
                    "    async def __aenter__(self) -> MockTornAPIWrapperAsync:",
                    "        return self",
                    "",
                    "    async def __aexit__(self, exc_type, exc, tb) -> None:",
                    "        await self.close()",
                ]
            )

        else:
            lines.extend(
                [
                    "",
                    "    def request(",
                    "        self,",
                    "        endpoint: str,",
                    "        params: dict | None,",
                    "    ) -> dict | str:",
                    "        return self._mock.request(endpoint, params)",
                ]
            )

        return lines


class ReportRenderer:
    def render(
        self,
        plan: GenerationPlan,
        example_warnings: Sequence[str],
        *,
        openapi_version: str,
    ) -> str:
        endpoint_count = sum(len(tag.routes) for tag in plan.tags)

        lines = [
            ("Torn OpenAPI mock report " f"(API {openapi_version})"),
            (
                f"Generated {len(plan.tags)} tags / "
                f"{endpoint_count} wrapper routes"
            ),
            "",
        ]

        for tag in plan.tags:
            lines.append(tag.name.upper())

            for route in tag.routes:
                lines.append(f"  {route.selection}")
                lines.append(f"    wrapper: {route.wrapper_method}")
                lines.append(f"    request: {route.request_path}")

                for variant in route.variants:
                    lines.append(f"    source: {variant.source_path}")

                    if variant.required_params:
                        lines.append(
                            "      requires request param: "
                            + ", ".join(variant.required_params)
                        )

                    if variant.forbidden_params:
                        lines.append(
                            "      forbids request param: "
                            + ", ".join(variant.forbidden_params)
                        )

            lines.append("")

        warnings = [
            *plan.warnings,
            *example_warnings,
        ]

        if warnings:
            lines.append("WARNINGS")

            for warning in warnings:
                lines.append(f"  - {warning}")

        return "\n".join(lines).rstrip() + "\n"


