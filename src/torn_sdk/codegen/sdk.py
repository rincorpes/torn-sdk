class ResourceMixinRenderer:
    """Render typed synchronous or asynchronous endpoint resource mixins."""

    def __init__(self, *, async_mode: bool) -> None:
        self.async_mode = async_mode

    def render(self, tag: TagIR) -> str:
        """Render the generated resource mixin for one Torn tag.

        Args:
            tag: Generated endpoints for one resource tag.

        Returns:
            Complete generated resource mixin source.
        """
        tag_pascal = PythonNames.pascal(tag.name)
        class_name = (
            f"GeneratedAsync{tag_pascal}ResourceMixin"
            if self.async_mode
            else f"Generated{tag_pascal}ResourceMixin"
        )
        decorator_name = "async_endpoint" if self.async_mode else "endpoint"

        model_names = sorted(
            {ep.response.public_model_name for ep in tag.endpoints}
        )
        alias_names = sorted(
            {
                alias
                for ep in tag.endpoints
                for param in ep.parameters
                for alias in param.type_ref.aliases
            }
        )
        custom_extractors = sorted(
            {
                ep.response.extraction.extractor
                for ep in tag.endpoints
                if ep.response.extraction.kind == "custom"
                and ep.response.extraction.extractor
            }
        )

        lines = generated_module_header(
            f"Typed {tag.name} resource mixins generated from the Torn OpenAPI specification."
        )
        lines.append(f"from torn_sdk.core.decorators import {decorator_name}")
        if model_names:
            lines.append(f"from torn_sdk.models.{tag.name} import (")
            for model in model_names:
                lines.append(f"    {model},")
            lines.append(")")
        if alias_names:
            lines.append("from torn_sdk.models.types import (")
            for alias in alias_names:
                lines.append(f"    {alias},")
            lines.append(")")
        if custom_extractors:
            lines.append("from torn_sdk.resources.extractors import (")
            for extractor in custom_extractors:
                lines.append(f"    {extractor},")
            lines.append(")")
        lines.extend(["", ""])
        lines.append(f"class {class_name}:")
        lines.extend(
            [
                '    """',
                f"    Typed {tag.name} endpoints generated from Torn OpenAPI.",
                "",
                "    Attributes:",
                "        endpoint (object): Underlying TornAPIWrapper endpoint.",
                "",
                "    Args:",
                "        endpoint (object): Endpoint supplied by the public resource class.",
                '    """',
            ]
        )
        if not tag.endpoints:
            lines.append("    pass")
            return "\n".join(lines).rstrip() + "\n"

        for endpoint in tag.endpoints:
            lines.extend(self._method(endpoint, decorator_name))
            lines.append("")
        lines.extend(custom_block("class", name=class_name, indent="    "))
        return "\n".join(lines).rstrip() + "\n"

    def _method(self, endpoint: EndpointIR, decorator_name: str) -> list[str]:
        decorator_args: list[str] = []
        extraction = endpoint.response.extraction
        if extraction.kind == "key":
            decorator_args.append(f"extract={extraction.key!r}")
        elif extraction.kind == "none":
            decorator_args.append("extract_default=False")
        elif extraction.kind == "custom":
            decorator_args.append(f"extractor={extraction.extractor}")

        default_wrapper_method = f"get_{endpoint.name}"
        if endpoint.wrapper_method != default_wrapper_method:
            decorator_args.insert(0, f"method={endpoint.wrapper_method!r}")

        decorator = f"@{decorator_name}({', '.join(decorator_args)})"
        lines = [f"    {decorator}"]
        async_prefix = "async " if self.async_mode else ""
        params = list(endpoint.parameters)
        path_params = [p for p in params if p.location == "path"]
        query_params = [p for p in params if p.location == "query"]

        signature_parts: list[str] = ["self"]
        signature_parts.extend(self._parameter(p) for p in path_params)
        if query_params:
            signature_parts.append("*")
            signature_parts.extend(self._parameter(p) for p in query_params)

        # Multiline signatures are deliberately explicit and formatter-friendly.
        lines.append(f"    {async_prefix}def {endpoint.name}(")
        for part in signature_parts:
            lines.append(f"        {part},")
        lines.append(f"    ) -> {endpoint.response.public_model_name}:")
        lines.extend(self._docstring(endpoint))
        lines.extend(
            custom_block(
                "method",
                name=endpoint.name,
                indent="        ",
            )
        )
        lines.append("        raise NotImplementedError")
        return lines

    @staticmethod
    def _docstring(endpoint: EndpointIR) -> list[str]:
        """Render endpoint docs in Google style from the OpenAPI contract."""
        lines = [
            '        """',
            f"        {endpoint.documentation or 'Call this Torn API endpoint.'}",
        ]
        if endpoint.parameters:
            lines.extend(["", "        Args:"])
            for parameter in endpoint.parameters:
                lines.append(
                    f"            {parameter.python_name} ({parameter.type_ref.code}): "
                    f"{parameter.location.title()} parameter for this endpoint."
                )
        lines.extend(
            [
                "",
                "        Returns:",
                f"            {endpoint.response.public_model_name}: Parsed API response.",
                "",
                "        Raises:",
                "            TornAPIWrapper.errors.APIError: If Torn rejects the request.",
                "            pydantic.ValidationError: If the response does not match the model.",
                '        """',
            ]
        )
        return lines

    @staticmethod
    def _parameter(parameter: ParameterIR) -> str:
        if parameter.default is MISSING:
            return f"{parameter.python_name}: {parameter.type_ref.code}"
        return f"{parameter.python_name}: {parameter.type_ref.code} = {parameter.default!r}"


class ResourceScaffoldRenderer:
    """Render public resources registered with the SDK resource registry."""

    def render(self, tag: str, *, async_mode: bool) -> str:
        """Render a public resource scaffold for a Torn tag.

        Args:
            tag: Normalized resource tag.
            async_mode: Whether to render the asynchronous resource.

        Returns:
            Complete public resource module source.
        """
        pascal = PythonNames.pascal(tag)
        suffix = "Async" if async_mode else ""
        wrapper_class = (
            "TornAPIWrapperAsync" if async_mode else "TornAPIWrapper"
        )
        endpoint_pkg = "endpoints_async" if async_mode else "endpoints"
        resource_base = "AsyncResource" if async_mode else "Resource"
        registry = (
            "AsyncResourceRegistry" if async_mode else "ResourceRegistry"
        )
        resource_class = f"{suffix}{pascal}Resource"
        generated_mixin = (
            f"GeneratedAsync{pascal}ResourceMixin"
            if async_mode
            else f"Generated{pascal}ResourceMixin"
        )
        generated_module = f"{tag}_async" if async_mode else tag
        lines = generated_module_header(
            f"Public typed {tag} resource registered with Torn SDK."
        )
        lines.extend(
            [
                f"from TornAPIWrapper import {wrapper_class}",
                f"from TornAPIWrapper.{endpoint_pkg}.{tag} import {pascal}",
                "",
                f"from torn_sdk.core.resource import {resource_base}, {registry}",
                f"from torn_sdk.resources._generated.{generated_module} import {generated_mixin}",
                "",
                "",
                f"class {resource_class}({generated_mixin}, {resource_base}[{pascal}]):",
                '    """',
                f"    Provide typed access to Torn {tag} endpoints.",
                "",
                "    Attributes:",
                f"        endpoint ({pascal}): Underlying TornAPIWrapper {tag} endpoint.",
                "",
                "    Args:",
                f"        wrapper ({wrapper_class}): Configured TornAPIWrapper client.",
                '    """',
                "",
                f"    def __init__(self, wrapper: {wrapper_class}) -> None:",
                *custom_block(
                    "method",
                    name=f"{resource_class}.__init__",
                    indent="        ",
                ),
                f"        super().__init__(wrapper.{tag})",
                "",
                *custom_block("class", name=resource_class, indent="    "),
                "",
                "",
                f"{registry}.register({tag!r}, {resource_class})",
            ]
        )
        return "\n".join(lines).rstrip() + "\n"


class ResourcePackageRenderer:
    """Render resources/__init__.py so importing torn_sdk.resources registers all resources."""

    def render(self, surface: ResourceSurface) -> str:
        """Render the public resource package initializer.

        Args:
            surface: Public resource modules to import.

        Returns:
            Complete ``resources`` package initializer source.
        """
        lines = generated_module_header(
            "Resource registrations generated from the Torn OpenAPI specification."
        )

        exports: list[str] = []
        for module in surface.modules:
            async_mode = module.endswith("_async")
            tag = module.removesuffix("_async")
            resource_class = (
                f"Async{PythonNames.pascal(tag)}Resource"
                if async_mode
                else f"{PythonNames.pascal(tag)}Resource"
            )
            lines.append(f"from .{module} import {resource_class}")
            exports.append(resource_class)
        if exports:
            lines.append("")

        lines.append("__all__ = [")
        for resource_class in exports:
            lines.append(f"    {resource_class!r},")
        lines.append("]")
        return "\n".join(lines).rstrip() + "\n"


class ClientRenderer:
    """Render the explicit typed client surface while preserving registry loading."""

    def __init__(self, *, async_mode: bool) -> None:
        self.async_mode = async_mode

    def render(
        self,
        tags: Sequence[str],
        *,
        customizations: ClientCustomizations = ClientCustomizations(),
    ) -> str:
        """Render either the sync or async client module for the given tags.

        Args:
            tags: Resource tags exposed by the client.
            customizations: Preserved user-owned client source regions.

        Returns:
            Complete generated client module source.
        """
        ordered_tags = tuple(sorted(tags))
        if self.async_mode:
            return self._render_async(ordered_tags, customizations)
        return self._render_sync(ordered_tags, customizations)

    @staticmethod
    def _resource_class(tag: str, *, async_mode: bool) -> str:
        pascal = PythonNames.pascal(tag)
        return f"Async{pascal}Resource" if async_mode else f"{pascal}Resource"

    def _client_docstring_lines(self, tags: Sequence[str]) -> list[str]:
        """Render a consistently indented Google-style client docstring."""
        mode = "asynchronous" if self.async_mode else "synchronous"
        wrapper = (
            "TornAPIWrapperAsync" if self.async_mode else "TornAPIWrapper"
        )
        raw = "AsyncRawNamespace" if self.async_mode else "RawNamespace"
        lines = [
            '    """',
            f"    Create a typed {mode} Torn API client.",
            "",
            "    Attributes:",
            f"        raw ({raw}): Escape hatch for raw wrapper access.",
        ]
        lines.extend(
            f"        {tag} (resources.{self._resource_class(tag, async_mode=self.async_mode)}): "
            f"Typed {tag} API resource."
            for tag in tags
        )
        lines.extend(
            [
                "",
                "    Args:",
                f"        api_key (str): Torn API key used by {wrapper}.",
                "        request_timeout (float | tuple[float, float]): Request timeout.",
                '    """',
            ]
        )
        return lines

    def _render_sync(
        self,
        tags: Sequence[str],
        customizations: ClientCustomizations,
    ) -> str:
        lines = [
            *generated_module_header(
                "Synchronous Torn client generated from the Torn OpenAPI specification."
            ),
            "from TornAPIWrapper import TornAPIWrapper",
            "",
            "from torn_sdk import resources",
            "from torn_sdk.base_client import BaseTornClient",
            "from torn_sdk.core.raw import RawNamespace",
            "from torn_sdk.core.resource import ResourceRegistry",
        ]

        lines.extend(
            [
                "",
                "",
                "class TornClient(",
                "    BaseTornClient[TornAPIWrapper, RawNamespace],",
                "):",
                *self._client_docstring_lines(tags),
                "    raw: RawNamespace",
            ]
        )

        if tags:
            lines.append("")
            for tag in tags:
                resource_class = self._resource_class(tag, async_mode=False)
                lines.append(f"    {tag}: resources.{resource_class}")

        lines.extend(
            [
                "",
                "    def __init__(",
                "        self,",
                "        api_key: str,",
                "        *,",
                "        request_timeout: float | tuple[float, float] = 10,",
                "    ) -> None:",
                *custom_block(
                    "method", name="TornClient.__init__", indent="        "
                ),
                "        wrapper = TornAPIWrapper(",
                "            api_key,",
                "            request_timeout=request_timeout,",
                "        )",
                "",
                "        super().__init__(",
                "            wrapper=wrapper,",
                "            raw=RawNamespace(wrapper),",
                "        )",
            ]
        )

        if tags:
            lines.append("")
            for tag in tags:
                resource_class = self._resource_class(tag, async_mode=False)
                lines.append(
                    f"        self.{tag} = resources.{resource_class}(wrapper)"
                )

        lines.extend(
            [
                "",
                "        self._load_resources(",
                "            ResourceRegistry.implementations(),",
                "        )",
                "",
                f"    {CLIENT_CUSTOM_CLASS_START}",
                *[
                    f"    {line}" if line else ""
                    for line in customizations.class_body
                ],
                f"    {CLIENT_CUSTOM_CLASS_END}",
            ]
        )
        return "\n".join(lines).rstrip() + "\n"

    def _render_async(
        self,
        tags: Sequence[str],
        customizations: ClientCustomizations,
    ) -> str:
        lines = [
            *generated_module_header(
                "Asynchronous Torn client generated from the Torn OpenAPI specification."
            ),
            "from types import TracebackType",
            "",
            "from TornAPIWrapper import TornAPIWrapperAsync",
            "",
            "from torn_sdk import resources",
            "from torn_sdk.base_client import BaseTornClient",
            "from torn_sdk.core.raw import AsyncRawNamespace",
            "from torn_sdk.core.resource import AsyncResourceRegistry",
        ]

        lines.extend(
            [
                "",
                "",
                "class AsyncTornClient(",
                "    BaseTornClient[TornAPIWrapperAsync, AsyncRawNamespace],",
                "):",
                *self._client_docstring_lines(tags),
                "    raw: AsyncRawNamespace",
            ]
        )

        if tags:
            lines.append("")
            for tag in tags:
                resource_class = self._resource_class(tag, async_mode=True)
                lines.append(f"    {tag}: resources.{resource_class}")

        lines.extend(
            [
                "",
                "    def __init__(",
                "        self,",
                "        api_key: str,",
                "        *,",
                "        request_timeout: float | tuple[float, float] = 10,",
                "    ) -> None:",
                *custom_block(
                    "method",
                    name="AsyncTornClient.__init__",
                    indent="        ",
                ),
                "        wrapper = TornAPIWrapperAsync(",
                "            api_key,",
                "            request_timeout=request_timeout,",
                "        )",
                "",
                "        super().__init__(",
                "            wrapper=wrapper,",
                "            raw=AsyncRawNamespace(wrapper),",
                "        )",
            ]
        )

        if tags:
            lines.append("")
            for tag in tags:
                resource_class = self._resource_class(tag, async_mode=True)
                lines.append(
                    f"        self.{tag} = resources.{resource_class}(wrapper)"
                )

        lines.extend(
            [
                "",
                "        self._load_resources(",
                "            AsyncResourceRegistry.implementations(),",
                "        )",
                "",
                "    async def close(self) -> None:",
                '        """Close the underlying asynchronous HTTP resources."""',
                *custom_block(
                    "method", name="AsyncTornClient.close", indent="        "
                ),
                "        await self._wrapper.close()",
                "",
                "    async def __aenter__(self) -> AsyncTornClient:",
                "        return self",
                "",
                "    async def __aexit__(",
                "        self,",
                "        exc_type: type[BaseException] | None,",
                "        exc: BaseException | None,",
                "        tb: TracebackType | None,",
                "    ) -> None:",
                "        await self.close()",
                "",
                f"    {CLIENT_CUSTOM_CLASS_START}",
                *[
                    f"    {line}" if line else ""
                    for line in customizations.class_body
                ],
                f"    {CLIENT_CUSTOM_CLASS_END}",
            ]
        )
        return "\n".join(lines).rstrip() + "\n"


class ResourceSurfacePlanner:
    """Determine which public resource modules are safe to import into package/client surfaces."""

    def __init__(self, sdk_root: Path) -> None:
        self.sdk_root = sdk_root

    def plan(
        self,
        global_plan: GenerationPlan,
        emission_plan: GenerationPlan,
        *,
        scaffold_resources: bool,
    ) -> ResourceSurface:
        """Determine which public resource modules should be imported.

        Args:
            global_plan: Complete discovered SDK plan.
            emission_plan: Plan being emitted by this invocation.
            scaffold_resources: Whether missing resource modules will be scaffolded.

        Returns:
            Public synchronous and asynchronous resource module surface.
        """
        known_tags = {tag.name for tag in global_plan.tags}
        emitted_tags = {tag.name for tag in emission_plan.tags}

        sync: set[str] = set()
        async_: set[str] = set()

        for tag in known_tags:
            sync_path = self.sdk_root / "resources" / f"{tag}.py"
            async_path = self.sdk_root / "resources" / f"{tag}_async.py"

            if sync_path.exists() or (
                scaffold_resources and tag in emitted_tags
            ):
                sync.add(tag)
            if async_path.exists() or (
                scaffold_resources and tag in emitted_tags
            ):
                async_.add(tag)

        return ResourceSurface(
            sync_tags=tuple(sorted(sync)),
            async_tags=tuple(sorted(async_)),
        )


class ReportRenderer:
    """Render a human-readable SDK generation report."""

    def render(self, plan: GenerationPlan) -> str:
        """Render a text report for the generated SDK plan.

        Args:
            plan: Generated SDK endpoint plan.

        Returns:
            Human-readable SDK generation report.
        """
        lines: list[str] = []
        for tag in plan.tags:
            lines.append(tag.name.upper())
            for ep in tag.endpoints:
                lines.append(f"  {ep.name}")
                lines.append(f"    paths: {', '.join(ep.source_paths)}")
                lines.append(f"    return: {ep.response.public_model_name}")
                lines.append(f"    wrapper: {ep.wrapper_method}")
                extraction = ep.response.extraction
                if extraction.kind == "key":
                    lines.append(f"    extraction: key {extraction.key!r}")
                elif extraction.kind == "custom":
                    lines.append(
                        f"    extraction: custom {extraction.extractor}"
                    )
                else:
                    lines.append("    extraction: none")
                if ep.parameters:
                    lines.append("    parameters:")
                    for p in ep.parameters:
                        default = (
                            "" if p.default is MISSING else f" = {p.default!r}"
                        )
                        wire_note = (
                            ""
                            if PythonNames.snake(p.python_name)
                            == PythonNames.snake(p.wire_name)
                            else f" -> API {p.wire_name!r}"
                        )
                        lines.append(
                            f"      {p.python_name}: {p.type_ref.code}{default} "
                            f"[{p.location}]{wire_note}"
                        )
            lines.append("")
        if plan.warnings:
            lines.append("WARNINGS")
            lines.extend(f"  - {warning}" for warning in plan.warnings)
        return "\n".join(lines).rstrip() + "\n"


class TornSDKGenerator:
    """Coordinate OpenAPI-driven Torn SDK source generation."""

    def __init__(
        self,
        document: OpenAPIDocument,
        sdk_root: Path,
        *,
        overrides: TornOverrides | None = None,
        check: bool = False,
        dry_run: bool = False,
        prune: bool = False,
        scaffold_resources: bool = False,
        strict: bool = False,
        skip_wrapper_check: bool = False,
    ) -> None:
        self.document = document
        self.sdk_root = sdk_root
        self.overrides = overrides or TornOverrides()
        self.check = check
        self.dry_run = dry_run
        self.prune = prune
        self.scaffold_resources = scaffold_resources
        self.strict = strict

        self.refs = RefResolver(document)
        self.literals = LiteralRegistry(self.overrides)
        self.types = SchemaTypeResolver(document, self.refs, self.literals)
        self.discovery = EndpointDiscovery(document)
        self.parameters = ParameterNormalizer(
            self.refs, self.types, self.overrides
        )
        self.responses = ResponsePlanner(self.refs, self.overrides)
        self.wrapper = TornAPIWrapperInspector(enabled=not skip_wrapper_check)
        self.ir_builder = IRBuilder(
            self.discovery,
            self.parameters,
            self.responses,
            self.overrides,
            self.wrapper,
            strict=self.strict,
        )
        self.models = ModelRenderer(
            document, self.refs, self.types, self.overrides
        )
        self.types_renderer = TypesRenderer()
        self.model_index = ModelIndexRenderer()
        self.sync_resources = ResourceMixinRenderer(async_mode=False)
        self.async_resources = ResourceMixinRenderer(async_mode=True)
        self.scaffolds = ResourceScaffoldRenderer()
        self.resource_package = ResourcePackageRenderer()
        self.sync_client = ClientRenderer(async_mode=False)
        self.client_async = ClientRenderer(async_mode=True)
        self.resource_surface = ResourceSurfacePlanner(sdk_root)
        self.reports = ReportRenderer()
        self.report_exporter = ReportExporter()

    def build_plan(
        self, selected_tags: set[str] | None = None
    ) -> GenerationPlan:
        """Build the SDK generation plan for the selected tags.

        Args:
            selected_tags: Optional normalized resource tags to include.

        Returns:
            Generated SDK endpoint plan.
        """
        return self.ir_builder.build(selected_tags)

    @staticmethod
    def _filter_plan(
        plan: GenerationPlan, selected_tags: set[str]
    ) -> GenerationPlan:
        normalized = {PythonNames.snake(tag) for tag in selected_tags}
        tags = [tag for tag in plan.tags if tag.name in normalized]
        warnings = [
            warning
            for warning in plan.warnings
            if any(
                warning.startswith(f"{tag}.")
                or warning.startswith(f"SKIPPED {tag}.")
                for tag in normalized
            )
        ]
        return GenerationPlan(tags=tags, warnings=warnings)

    def _build_global_plan(self) -> GenerationPlan:
        # Shared artifacts such as models/types.py must be derived from the entire
        # OpenAPI document, even when the caller asks to emit only one tag. Use a
        # non-strict planner here so an unrelated unsupported endpoint cannot block
        # a targeted generation run.
        builder = IRBuilder(
            self.discovery,
            self.parameters,
            self.responses,
            self.overrides,
            self.wrapper,
            strict=False,
        )
        return builder.build(None)

    def _discover_global_model_literals(self, plan: GenerationPlan) -> None:
        # Parameter parsing discovers parameter enums while building the plan. Model
        # field enums are discovered during model rendering, so render every planned
        # response once in memory to make the global Literal registry complete.
        # Unsupported model-rendering edge cases are ignored here; they will still
        # fail normally if that endpoint is part of the selected emission plan.
        for tag in plan.tags:
            for endpoint in tag.endpoints:
                try:
                    self.models.render_endpoint_model(endpoint)
                except ReviewRequired:
                    continue

    def generate(
        self, selected_tags: set[str] | None = None
    ) -> tuple[GenerationPlan, GeneratedFileManager]:
        """Generate SDK sources and return the plan plus file changes.

        Args:
            selected_tags: Optional normalized resource tags to generate.

        Returns:
            Generated SDK plan and tracked file changes.

        Raises:
            ReviewRequired: If strict generation finds an unsafe selected endpoint.
        """
        # Always perform global discovery first. `types.py` is a package-global
        # artifact and must not shrink simply because this run selected one tag.
        global_plan = self._build_global_plan()
        self._discover_global_model_literals(global_plan)

        if selected_tags:
            if self.strict:
                # Preserve strict semantics for the tags the user explicitly asked
                # to generate, without making unrelated tags block the run.
                plan = self.build_plan(selected_tags)
            else:
                plan = self._filter_plan(global_plan, selected_tags)
        else:
            plan = self.build_plan(None) if self.strict else global_plan

        files = GeneratedFileManager(
            self.sdk_root,
            check=self.check,
            dry_run=self.dry_run,
            prune=self.prune,
        )
        formatter = GeneratedSourceFormatter(self.sdk_root)

        def emit(relative: Path, content: str) -> None:
            if GENERATED_HEADER in content:
                content = (
                    content.rstrip()
                    + "\n\n"
                    + "\n".join(custom_block("footer"))
                    + "\n"
                )
            content = merge_custom_blocks(self.sdk_root / relative, content)
            files.emit(relative, formatter.format(content))

        # Render selected models for emission. Global model discovery above has
        # already populated the shared Literal registry from every supported tag.
        model_outputs: list[tuple[Path, str]] = []
        for tag in plan.tags:
            for endpoint in tag.endpoints:
                relative = Path("models") / tag.name / f"{endpoint.name}.py"
                model_outputs.append(
                    (relative, self.models.render_endpoint_model(endpoint))
                )

        for relative, content in model_outputs:
            emit(relative, content)

        emit(
            Path("models") / "types.py",
            self.types_renderer.render(self.literals.aliases),
        )

        for tag in plan.tags:
            emit(
                Path("models") / tag.name / "__init__.py",
                self.model_index.render(tag.endpoints),
            )
            emit(
                Path("resources") / "_generated" / f"{tag.name}.py",
                self.sync_resources.render(tag),
            )
            emit(
                Path("resources") / "_generated" / f"{tag.name}_async.py",
                self.async_resources.render(tag),
            )
            if self.scaffold_resources:
                emit(
                    Path("resources") / f"{tag.name}.py",
                    self.scaffolds.render(tag.name, async_mode=False),
                )
                emit(
                    Path("resources") / f"{tag.name}_async.py",
                    self.scaffolds.render(tag.name, async_mode=True),
                )

        # Public resources and clients are package-global surfaces. Build them from
        # resource modules that already exist plus modules scheduled to be scaffolded
        # in this run. This lets tags be added incrementally without generating
        # imports for resource files that do not exist yet.
        surface = self.resource_surface.plan(
            global_plan,
            plan,
            scaffold_resources=self.scaffold_resources,
        )
        emit(
            Path("resources") / "__init__.py",
            self.resource_package.render(surface),
        )
        sync_client_path = Path("client.py")
        emit(
            sync_client_path,
            self.sync_client.render(
                surface.sync_tags,
                customizations=read_client_customizations(
                    self.sdk_root / sync_client_path
                ),
            ),
        )
        async_client_path = Path("client_async.py")
        emit(
            async_client_path,
            self.client_async.render(
                surface.async_tags,
                customizations=read_client_customizations(
                    self.sdk_root / async_client_path
                ),
            ),
        )
        # v5 briefly generated async_client.py. Treat that machine-owned legacy
        # filename as stale so --prune cleanly migrates projects to client_async.py.
        files.find_stale_paths([Path("async_client.py")])

        if selected_tags:
            # Partial generation owns only the selected tag model directories. Do
            # not consider other tags stale, and never prune their generated files.
            files.find_stale(Path("models") / tag.name for tag in plan.tags)
        else:
            # A full generation pass owns the entire generated surface and can
            # safely identify removed tags/endpoints.
            files.find_stale(
                [
                    Path("models"),
                    Path("resources") / "_generated",
                ]
            )
        return plan, files
