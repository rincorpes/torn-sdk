class EndpointDiscovery:
    def __init__(self, document: OpenAPIDocument) -> None:
        self.document = document

    def discover(
        self,
        selected_tags: set[str] | None,
    ) -> list[RawOperation]:
        result: list[RawOperation] = []

        for path, path_item in self.document.paths.items():
            if not isinstance(path_item, Mapping):
                continue

            for method, operation in path_item.items():
                if method.lower() not in HTTP_METHODS:
                    continue
                if not isinstance(operation, Mapping):
                    continue

                tags = operation.get("tags")
                if not isinstance(tags, list):
                    continue

                for raw_tag in tags:
                    tag = PythonNames.snake(str(raw_tag))

                    if selected_tags and tag not in selected_tags:
                        continue

                    result.append(
                        RawOperation(
                            tag=tag,
                            selection=self._selection(
                                path,
                                tag,
                                operation,
                            ),
                            path=path,
                            http_method=method.lower(),
                            operation=operation,
                        )
                    )

        return result

    def _selection(
        self,
        path: str,
        tag: str,
        operation: Mapping[str, Any],
    ) -> str:
        parts = [part for part in path.strip("/").split("/") if part]

        static = [
            part
            for part in parts
            if not (part.startswith("{") and part.endswith("}"))
        ]

        if static and PythonNames.snake(static[0]) == tag:
            static = static[1:]

        if static:
            return PythonNames.snake(static[-1])

        # Generic root endpoints are intentionally ignored unless they map
        # cleanly to a named wrapper method.
        operation_id = str(operation.get("operationId", ""))
        if operation_id:
            candidate = re.sub(
                r"^(get|post|put|patch|delete)",
                "",
                operation_id,
                flags=re.I,
            )
            return PythonNames.snake(candidate)

        raise ReviewRequired(f"Cannot derive selection for {path}")


