class FileWriter:
    def write(
        self,
        path: Path,
        content: str,
        *,
        check: bool,
    ) -> bool:
        previous = path.read_text(encoding="utf-8") if path.exists() else None

        changed = previous != content

        if changed and not check:
            path.parent.mkdir(
                parents=True,
                exist_ok=True,
            )
            path.write_text(
                content,
                encoding="utf-8",
            )

        return changed


