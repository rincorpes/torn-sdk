class TornAPIWrapperInspector:
    """Inspect TornAPIWrapper by the request path each method actually calls.

    The wrapper method name is deliberately *not* derived from the SDK/OpenAPI
    Python name. TornAPIWrapper often flattens compound selections, for example
    OpenAPI ``revivesFull`` -> SDK ``revives_full`` -> wrapper
    ``get_revivesfull``.
    """

    _REQUEST_RE = re.compile(
        r"""(?:self\.)?api\.request\(\s*[furbFURB]*["']([^"']+)["']"""
    )

    def __init__(self, *, enabled: bool = True) -> None:
        self.enabled = enabled
        self._parameter_map: Mapping[str, str] = {}
        self._module_cache: dict[tuple[str, str], Any] = {}
        self._resource_cache: dict[tuple[str, str], Any] = {}
        self._method_index_cache: dict[
            tuple[str, str], dict[str, list[tuple[str, Any, str]]]
        ] = {}

        if enabled:
            self._load_parameter_map()

    def _load_parameter_map(self) -> None:
        try:
            module = importlib.import_module("TornAPIWrapper.params.map")
        except Exception as exc:
            raise MockCodegenError(
                "TornAPIWrapper must be installed for compatibility checks. "
                "Use --skip-wrapper-check only for OpenAPI-only debugging."
            ) from exc

        mapping = getattr(module, "parameter_map", None)

        if not isinstance(mapping, Mapping):
            raise MockCodegenError(
                "TornAPIWrapper.params.map.parameter_map is unavailable"
            )

        self._parameter_map = mapping

    def inspect_endpoint(
        self,
        tag: str,
        preferred_method: str,
        openapi_parameters: Sequence[ParameterSpec],
        source_paths: Sequence[str],
        fallback_request_path: str,
    ) -> WrapperEndpoint:
        if not self.enabled:
            return WrapperEndpoint(
                method_name=preferred_method,
                request_path=fallback_request_path,
                request_parameter_names={
                    param.api_name: param.api_name
                    for param in openapi_parameters
                },
            )

        sync_name, sync_method, sync_path = self._resolve_method(
            "endpoints",
            tag,
            preferred_method,
            source_paths,
        )
        async_name, async_method, async_path = self._resolve_method(
            "endpoints_async",
            tag,
            preferred_method,
            source_paths,
        )

        if sync_name != async_name:
            raise WrapperUnsupported(
                f"sync/async wrapper methods differ for {tag}: "
                f"sync={sync_name}, async={async_name}"
            )

        if self._normalize_request_path(
            sync_path
        ) != self._normalize_request_path(async_path):
            raise WrapperUnsupported(
                f"sync/async request paths differ for {tag}.{sync_name}: "
                f"sync={sync_path}, async={async_path}"
            )

        sync_signature = self._clean_signature(sync_method)
        async_signature = self._clean_signature(async_method)

        if self._signature_shape(sync_signature) != self._signature_shape(
            async_signature
        ):
            raise WrapperUnsupported(
                f"sync/async signatures differ for {tag}.{sync_name}"
            )

        remaining = list(openapi_parameters)
        request_names: dict[str, str] = {}
        notes: list[str] = []

        for wrapper_name, wrapper_param in sync_signature.items():
            request_name = str(
                self._parameter_map.get(
                    wrapper_name,
                    wrapper_name,
                )
            )

            match = self._match(
                wrapper_name,
                request_name,
                remaining,
            )

            if match is None:
                if wrapper_param.default is not inspect.Parameter.empty:
                    notes.append(
                        f"{tag}.{sync_name}: optional wrapper parameter "
                        f"{wrapper_name!r} is not represented by OpenAPI"
                    )
                    continue

                raise WrapperUnsupported(
                    f"required wrapper parameter {wrapper_name!r} "
                    f"cannot be mapped to OpenAPI"
                )

            remaining.remove(match)
            request_names[match.api_name] = request_name

        for param in remaining:
            if param.required:
                raise WrapperUnsupported(
                    f"{sync_name}() does not expose required API "
                    f"parameter {param.api_name!r}"
                )

            notes.append(
                f"{tag}.{sync_name}: optional API parameter "
                f"{param.api_name!r} is unsupported by TornAPIWrapper"
            )

        return WrapperEndpoint(
            method_name=sync_name,
            request_path=sync_path,
            request_parameter_names=request_names,
            notes=tuple(notes),
        )

    def _module(self, package: str, tag: str) -> Any:
        key = (package, tag)
        if key in self._module_cache:
            return self._module_cache[key]

        module_name = f"TornAPIWrapper.{package}.{tag}"
        try:
            module = importlib.import_module(module_name)
        except Exception as exc:
            raise WrapperUnsupported(
                f"missing wrapper module {module_name}"
            ) from exc

        self._module_cache[key] = module
        return module

    def _resource_type(self, package: str, tag: str) -> Any:
        key = (package, tag)
        if key in self._resource_cache:
            return self._resource_cache[key]

        module = self._module(package, tag)
        resource_name = PythonNames.pascal(tag)
        resource = getattr(module, resource_name, None)

        if resource is None:
            raise WrapperUnsupported(
                f"{module.__name__} has no {resource_name} class"
            )

        self._resource_cache[key] = resource
        return resource

    def _resolve_method(
        self,
        package: str,
        tag: str,
        preferred_method: str,
        source_paths: Sequence[str],
    ) -> tuple[str, Any, str]:
        resource = self._resource_type(package, tag)
        index = self._method_index(package, tag)
        targets = {
            self._normalize_request_path(path) for path in source_paths if path
        }

        matches: list[tuple[str, Any, str]] = []
        for target in sorted(targets):
            matches.extend(index.get(target, ()))
        matches = self._unique_methods(matches)

        if len(matches) == 1:
            return matches[0]
        if len(matches) > 1:
            raise WrapperUnsupported(
                f"multiple wrapper methods map to {sorted(targets)}: "
                f"{[name for name, _, _ in matches]}"
            )

        exact = getattr(resource, preferred_method, None)
        if exact is not None and callable(exact):
            path = self._request_path_from_method(exact)
            if path is not None:
                return preferred_method, exact, path

        # Separator-insensitive fallback: get_revives_full == get_revivesfull.
        target_key = self._method_key(preferred_method)
        name_matches: list[tuple[str, Any, str]] = []
        for name, method in inspect.getmembers(resource, predicate=callable):
            if (
                not name.startswith("get_")
                or self._method_key(name) != target_key
            ):
                continue
            path = self._request_path_from_method(method)
            if path is not None:
                name_matches.append((name, method, path))

        name_matches = self._unique_methods(name_matches)
        if len(name_matches) == 1:
            return name_matches[0]
        if len(name_matches) > 1:
            raise WrapperUnsupported(
                f"ambiguous wrapper method match for {tag}.{preferred_method}: "
                f"{[name for name, _, _ in name_matches]}"
            )

        side = "async" if package.endswith("_async") else "sync"
        raise WrapperUnsupported(
            f"TornAPIWrapper {side} {PythonNames.pascal(tag)} has no method "
            f"mapped to {', '.join(sorted(source_paths)) or '<unknown path>'} "
            f"(preferred {preferred_method}())"
        )

    def _method_index(
        self,
        package: str,
        tag: str,
    ) -> dict[str, list[tuple[str, Any, str]]]:
        key = (package, tag)
        cached = self._method_index_cache.get(key)
        if cached is not None:
            return cached

        resource = self._resource_type(package, tag)
        index: dict[str, list[tuple[str, Any, str]]] = defaultdict(list)

        for name, method in inspect.getmembers(resource, predicate=callable):
            if not name.startswith("get_"):
                continue
            request_path = self._request_path_from_method(method)
            if request_path is None:
                continue
            index[self._normalize_request_path(request_path)].append(
                (name, method, request_path)
            )

        result = dict(index)
        self._method_index_cache[key] = result
        return result

    @classmethod
    def _request_path_from_method(cls, method: Any) -> str | None:
        try:
            source = inspect.getsource(method)
        except (OSError, TypeError):
            return None
        match = cls._REQUEST_RE.search(source)
        return match.group(1) if match else None

    @staticmethod
    def _normalize_request_path(path: str) -> str:
        parts = [
            part
            for part in path.strip().split("/")
            if part and not (part.startswith("{") and part.endswith("}"))
        ]
        return "/" + "/".join(parts).casefold()

    @staticmethod
    def _method_key(method_name: str) -> str:
        if method_name.startswith("get_"):
            method_name = method_name[4:]
        return re.sub(r"[^0-9a-z]+", "", method_name.casefold())

    @staticmethod
    def _unique_methods(
        items: Sequence[tuple[str, Any, str]],
    ) -> list[tuple[str, Any, str]]:
        result: dict[str, tuple[Any, str]] = {}
        for name, method, path in items:
            result[name] = (method, path)
        return [
            (name, method, path) for name, (method, path) in result.items()
        ]

    @staticmethod
    def _clean_signature(
        method: Any,
    ) -> dict[str, inspect.Parameter]:
        return {
            name: param
            for name, param in inspect.signature(method).parameters.items()
            if name != "self"
        }

    @staticmethod
    def _signature_shape(
        signature: Mapping[str, inspect.Parameter],
    ) -> tuple[tuple[str, Any, Any], ...]:
        return tuple(
            (
                name,
                param.kind,
                (
                    "<required>"
                    if param.default is inspect.Parameter.empty
                    else repr(param.default)
                ),
            )
            for name, param in signature.items()
        )

    def _match(
        self,
        wrapper_name: str,
        request_name: str,
        candidates: Sequence[ParameterSpec],
    ) -> ParameterSpec | None:
        exact_python = [
            param for param in candidates if param.python_name == wrapper_name
        ]

        if len(exact_python) == 1:
            return exact_python[0]

        exact_wire = [
            param
            for param in candidates
            if PythonNames.snake(param.api_name)
            == PythonNames.snake(request_name)
        ]

        if len(exact_wire) == 1:
            return exact_wire[0]

        # If there is only one path parameter, an id-ish wrapper parameter is
        # unambiguous even when TornAPIWrapper's parameter_map is behind OpenAPI.
        if request_name in {"id", "ids"} or wrapper_name.endswith(
            ("_id", "_ids")
        ):
            path = [param for param in candidates if param.location == "path"]
            if len(path) == 1:
                return path[0]

        return None


